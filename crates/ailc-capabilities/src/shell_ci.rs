    // ───────────── общие инварианты ─────────────

    #[test]
    fn все_встроенные_паттерны_компилируются() {
        // Несобравшийся литерал выключает СВОЁ правило (Matcher::Never), поэтому проверка
        // должна валить непрерывную интеграцию, а не деградировать молча у пользователя.
        for cap in [shell_scan(), ci_scan()] {
            for r in cap.rules() {
                assert!(
                    !r.matcher.is_disabled(),
                    "паттерн правила {} не скомпилировался",
                    r.id
                );
            }
        }
    }

    #[test]
    fn все_правила_имеют_cwe_в_сообщении() {
        for r in shell_rules().into_iter().chain(ci_rules()) {
            assert!(
                r.message.contains("CWE-"),
                "правило {} обязано ссылаться на класс слабости CWE",
                r.id
            );
        }
    }

    #[test]
    fn нет_дублей_идентификаторов_правил() {
        let mut ids: Vec<&str> = shell_rules().iter().map(|r| r.id).collect();
        ids.extend(ci_rules().iter().map(|r| r.id));
        let n = ids.len();
        ids.sort_unstable();
        ids.dedup();
        assert_eq!(
            ids.len(),
            n,
            "идентификаторы правил командных сценариев и рабочих процессов должны быть уникальны"
        );
    }
