//! Сканеры командных сценариев (shell) и рабочих процессов непрерывной интеграции
//! (Continuous Integration, далее CI): корзина «детектируется в коде» поверх общего
//! `ScanEngine`. Тонкие конфиги (таблицы правил), без новой логики обхода и матча.
//!
//! ПРИЧИНА появления модуля. До него набор правил не покрывал ни одного командного
//! сценария и ни одного описания рабочего процесса, хотя именно эти два артефакта суть
//! самые частые точки компрометации цепочки поставки программного обеспечения: сценарий
//! установки исполняется с правами разработчика или сборочного агента, а рабочий процесс
//! исполняется с токеном репозитория и доступом к секретам. Дефект в них не требует
//! эксплуатации уязвимости в продукте, он сразу даёт исполнение произвольного кода.
//!
//! ПРИНЦИП тот же, что и в корне крейта: инструмент есть таблица правил. Паттерны
//! СТРОГИЕ и требуют реальной формы записи (команда в позиции команды, конкретный флаг,
//! конкретное поле события), а не случайного вхождения слова. Для этого продукта ложное
//! срабатывание дороже пропуска: находка, которую человек признал вымышленной, подрывает
//! доверие ко всему вердикту, тогда как пропуск оставляет систему в том же состоянии, в
//! каком она была до проверки. Поэтому там, где выбор стоял между охватом и точностью,
//! выбрана точность, а сознательно принятые пропуски описаны в комментарии к правилу.
//!
//! ОТСУТСТВИЕ ОТРИЦАНИЯ В ПАТТЕРНАХ. Крейт `regex` не поддерживает просмотр вперёд,
//! поэтому оговорка вида «совпало, но не в таком-то контексте» выражается обёрткой
//! `Matcher::except`, которая отбрасывает совпадение, если паттерн-исключение совпал с
//! текстом находки. Так закреплено требование не считать находкой закрепление действия по
//! отпечатку коммита и не считать находкой строку комментария сценария.
//!
//! АНТИ-ДУБЛИРОВАНИЕ. Правило `dockerfile-curl-bash` в `security_extra.rs` покрывает тот
//! же класс «загрузка по сети с немедленным исполнением», но применяется исключительно к
//! файлам сборки образа (расширение `dockerfile`), тогда как правило
//! `shell-curl-pipe-shell` применяется к расширениям `sh`, `bash` и `zsh`. Множества
//! файлов не пересекаются, поэтому двойного счёта одной и той же строки не возникает.
//! Правило `shell-eval-variable` намеренно НЕ включает `eval` в список команд правила
//! `shell-unquoted-var`: иначе одна и та же строка порождала бы две находки разной
//! важности, что для человека выглядит как шум, а для отчёта означает двойной счёт одного
//! дефекта. Исполнение через `eval` покрыто отдельным правилом более высокой важности.
//!
//! ОХВАТ СКРЫТЫХ КАТАЛОГОВ. Обход в режиме `WalkMode::Code` отбрасывает любой элемент,
//! имя которого начинается с точки, а рабочие процессы живут ровно в таких местах:
//! GitHub Actions в каталоге `.github/workflows`, GitLab CI в файле `.gitlab-ci.yml`.
//! Поэтому сканер рабочих процессов создаётся с режимом `WalkMode::Ci`, раскрывающим
//! каталоги описаний процессов и читающим их скрытые файлы. Без этого режима проверка
//! молча не находила бы ни одного целевого файла, а это опаснее отсутствующей проверки:
//! ноль находок читается как чистота, тогда как на деле не просмотрено ничего.

use ailc_contracts::{Family, Severity};
use ailc_core::engines::scan::{Matcher, Rule};
use ailc_core::engines::walk::WalkMode;
use ailc_core::registry::Registry;

use crate::{scan_manifest, ScanCapability};

/// Расширения командных сценариев. Отдельная константа, чтобы список расширений был задан
/// ровно один раз и не расходился между правилами одной таблицы.
const SHELL_EXTS: &[&str] = &["sh", "bash", "zsh"];

/// Расширения описаний рабочих процессов. Формат один и тот же (YAML), различаются лишь
/// принятые в экосистемах написания расширения.
const CI_EXTS: &[&str] = &["yml", "yaml"];

// ───────────────────────── security.scan/shell ─────────────────────────

/// Опасные конструкции командных сценариев: незакавыченная подстановка переменной в
/// позиции аргумента разрушающей команды, исполнение строки через `eval`, загрузка кода из
/// сети с немедленным исполнением, загрузка с отключённой проверкой сертификата, временный
/// файл по предсказуемому пути, явное подавление ошибки шага установки или сборки и выдача
/// прав записи всему миру.
pub fn shell_scan() -> ScanCapability {
    ScanCapability::new(
        scan_manifest(
            "security.scan/shell",
            Family::Security,
            "Опасные конструкции командных сценариев (расширения sh, bash, zsh): незакавыченная подстановка переменной в аргументе разрушающей команды, исполнение строки через eval, загрузка кода из сети конвейером в оболочку, загрузка с отключённой проверкой сертификата, временный файл по предсказуемому пути вместо mktemp, явное подавление ошибки шага установки или сборки, выдача прав записи всем пользователям. Покрытие паттерновое и построчное: конструкции, разорванные продолжением строки, могут остаться вне охвата, поэтому ручной обзор сценариев развёртывания остаётся желательным.",
        ),
        shell_rules(),
    )
}

/// Таблица правил `security.scan/shell`. Вынесена отдельной функцией по образцу
/// `web_security.rs`, чтобы тесты могли брать конкретное правило по идентификатору и
/// проверять его матчер, не обходя дерево файлов.
fn shell_rules() -> Vec<Rule> {
    use Severity::{Critical, High, Low, Medium};
    vec![
        // ── Незакавыченная подстановка переменной в опасной позиции ────────────
        // Оболочка выполняет над результатом подстановки расщепление слов по символам
        // разделителя и подстановку имён файлов по образцу. Значение переменной поэтому
        // перестаёт быть одним аргументом и превращается в несколько аргументов либо в
        // образец, раскрываемый по содержимому каталога. Для разрушающей команды это
        // означает воздействие не на тот объект, который имел в виду автор: пустая
        // переменная в записи вида `rm -rf $DIR/` оставляет команду удаления с корневым
        // путём, а значение с пробелом превращает один путь в несколько.
        //
        // Строгость обеспечена тремя условиями. Первое: команда обязана стоять в ПОЗИЦИИ
        // КОМАНДЫ, то есть в начале строки либо после разделителя команд или ключевого
        // слова управляющей конструкции, поэтому упоминание слова в середине строки
        // находкой не является. Второе: между командой и подстановкой допускаются только
        // цельные лексемы (опция, закавыченный аргумент, слово без знака доллара),
        // поэтому закавыченная подстановка не может быть принята за незакавыченную.
        // Третье: знак доллара обязан следовать сразу за пробельным разделителем, что и
        // отличает `rm -rf $DIR` от безопасного `rm -rf "$DIR"`.
        //
        // Команда `eval` в перечень сознательно не включена: она покрыта следующим
        // правилом с важностью «критическая», и включение её сюда дало бы две находки на
        // одну строку. Команда `mkdir` также исключена, поскольку запись вида
        // `mkdir -p $HOME/bin` встречается в сценариях повсеместно, а последствие
        // расщепления слов для неё сводится к созданию лишнего каталога.
        Rule {
            id: "shell-unquoted-var",
            severity: High,
            exts: SHELL_EXTS,
            matcher: Matcher::regex(
                r#"(?:^|[;&|(]|\b(?:then|do|else)[ \t])[ \t]*(?:sudo[ \t]+)?(?:rm|cp|mv|chown|chgrp|chmod|ln|dd|tar|install|source)\b(?:[ \t]+(?:"[^"]*"|'[^']*'|-[-A-Za-z0-9]+|[^\s$'";|&]+))*[ \t]+\$\{?[A-Za-z_]"#,
            )
            .except(r"^[ \t]*#"),
            message: "Подстановка переменной без кавычек в аргументе разрушающей команды: оболочка выполняет расщепление слов и подстановку имён файлов, поэтому значение переменной превращается в дополнительные аргументы, а пустое значение оставляет команду без цели (CWE-78 внедрение команд операционной системы; OWASP A03:2021 Injection). Заключайте подстановку в двойные кавычки, проверяйте переменную на пустоту и завершайте перечень опций двумя дефисами.",
        },
        // ── Исполнение строки через eval ──────────────────────────────────────
        // Конструкция `eval` заново разбирает свой аргумент как текст программы, поэтому
        // любые метасимволы, попавшие в значение переменной или в вывод подстановки
        // команды, исполняются. Кавычки здесь не защищают: они лишь откладывают разбор на
        // один шаг, а `eval` этот шаг и выполняет. Именно поэтому важность критическая, а
        // не высокая, и именно поэтому находкой является само сочетание `eval` с
        // подстановкой, а не только незакавыченная её форма.
        Rule {
            id: "shell-eval-variable",
            severity: Critical,
            exts: SHELL_EXTS,
            matcher: Matcher::regex(
                r#"(?:^|[;&|(]|\b(?:then|do|else)[ \t])[ \t]*(?:sudo[ \t]+)?eval\b[^\n]*(?:\$[A-Za-z_{(]|`)"#,
            )
            .except(r"^[ \t]*#"),
            message: "Исполнение строки через eval с подстановкой переменной или подстановкой команды: аргумент заново разбирается как текст программы, поэтому метасимволы из значения переменной исполняются, и кавычки от этого не защищают (CWE-95 внедрение кода в динамически вычисляемый код). Замените eval вызовом функции, массивом аргументов или конструкцией case с явным перечнем допустимых значений.",
        },
        // ── Загрузка по сети с немедленным исполнением ─────────────────────────
        // Содержимое, полученное по сети, передаётся оболочке напрямую, поэтому оно нигде
        // не сохраняется, не проверяется по контрольной сумме и не может быть предъявлено
        // при разборе инцидента. Подмена ответа сервера, компрометация зеркала или
        // перехват соединения немедленно превращаются в исполнение произвольного кода с
        // правами вызывающего. Промежуточный конвейер в паттерне запрещён: требуется,
        // чтобы оболочка стояла непосредственно за первым знаком конвейера, что и
        // отличает исполнение от разбора вывода сторонними средствами.
        Rule {
            id: "shell-curl-pipe-shell",
            severity: High,
            exts: SHELL_EXTS,
            matcher: Matcher::regex(
                r"(?i)\b(?:curl|wget)\b[^\n|]*\|[ \t]*(?:sudo[ \t]+(?:-[A-Za-z]+[ \t]+)*)?(?:ba|z|k|da)?sh\b",
            )
            .except(r"^[ \t]*#"),
            message: "Загрузка по сети с немедленным исполнением в оболочке: код нигде не сохраняется и не проверяется по контрольной сумме, поэтому подмена ответа сервера равносильна исполнению произвольного кода (CWE-494 загрузка кода без проверки целостности; OWASP A08:2021 Software and Data Integrity Failures). Сохраните файл, сверьте его контрольную сумму или подпись и только затем исполняйте.",
        },
        // ── Загрузка с отключённой проверкой сертификата ──────────────────────
        // Отключение проверки сертификата снимает единственное средство, отличающее
        // подлинный сервер от посредника, поэтому загруженный артефакт перестаёт быть
        // доверенным независимо от того, по какому протоколу он получен. Важность
        // «средняя», а не «высокая», поскольку сама по себе строка означает ослабление
        // защиты канала, а не непосредственное исполнение чужого кода.
        //
        // Паттерн различает краткую и полную форму опции. Краткая форма распознаётся как
        // связка кратких опций, ЗАКАНЧИВАЮЩАЯСЯ буквой k, поэтому опции вида `--key` или
        // `--cacert` находкой не являются: между дефисом и буквой k в них стоит дефис,
        // который в класс символов краткой связки не входит.
        Rule {
            id: "shell-insecure-download",
            severity: Medium,
            exts: SHELL_EXTS,
            matcher: Matcher::regex(
                r"(?i)\bcurl\b[^\n]*(?:[ \t]--insecure\b|[ \t]-[A-Za-z]*k(?:[ \t]|$))|\bwget\b[^\n]*[ \t]--no-check-certificate\b",
            )
            .except(r"^[ \t]*#"),
            message: "Загрузка по сети с отключённой проверкой сертификата: подлинность сервера не подтверждается, поэтому содержимое может быть подменено посредником (CWE-295 ненадлежащая проверка сертификата; OWASP A07:2021 Identification and Authentication Failures). Уберите отключение проверки, а при работе с внутренним удостоверяющим центром укажите его корневой сертификат явной опцией.",
        },
        // ── Временный файл по предсказуемому пути ──────────────────────────────
        // Каталог временных файлов доступен на запись всем пользователям системы, поэтому
        // имя, которое можно предсказать заранее, позволяет постороннему процессу создать
        // на этом пути символическую ссылку и подставить свой объект до того, как сценарий
        // обратится к нему. Идентификатор процесса предсказуемости не устраняет: диапазон
        // его значений мал и перебирается. Признаком является КОНТЕКСТ ЗАПИСИ, то есть
        // присваивание пути переменной, перенаправление вывода или явное создание файла;
        // одно лишь упоминание пути находкой не считается. Оговорка снимает совпадение,
        // если в строке присутствует вызов mktemp, поскольку тогда предсказуемая часть
        // служит только образцом имени.
        Rule {
            id: "shell-predictable-temp",
            severity: Medium,
            exts: SHELL_EXTS,
            matcher: Matcher::regex(
                r#"(?:[A-Za-z_][A-Za-z0-9_]*=|>>?[ \t]*|(?:^|[;&|(])[ \t]*(?:touch|tee|mkfifo)[ \t]+)["']?/tmp/(?:\$\$|[A-Za-z0-9_][A-Za-z0-9_.-]*)"#,
            )
            .except(r"mktemp|^[ \t]*#"),
            message: "Временный файл создаётся по предсказуемому пути в общедоступном каталоге: посторонний процесс может заранее занять это имя символической ссылкой и подменить объект операции (CWE-377 небезопасный временный файл; OWASP A01:2021 Broken Access Control). Создавайте временный файл или каталог вызовом mktemp и удаляйте его обработчиком выхода.",
        },
        // ── Явное подавление ошибки шага установки или сборки ──────────────────
        // Исходный замысел состоял в том, чтобы отмечать сценарий длиннее двадцати строк,
        // не устанавливающий режим немедленного прекращения работы при ошибке. Такое
        // правило требует ОТРИЦАНИЯ по всему файлу, а именно утверждения «нигде не
        // встречается set -e», которое регулярным выражением невыразимо: `regex` не
        // поддерживает просмотр вперёд, а `Matcher::except` умеет снимать совпадение, но
        // не умеет порождать находку из его отсутствия. Поэтому вместо отрицания правило
        // фиксирует ПОЛОЖИТЕЛЬНЫЙ признак того же дефекта: явное подавление кода возврата
        // у шага установки или сборки. Такой шаг молча продолжает работу на неполном
        // результате, и последующие шаги выполняются над неверным состоянием, а сборка
        // объявляется успешной. Важность низкая: это дефект дисциплины обработки ошибок,
        // а не непосредственная уязвимость.
        //
        // Перечень команд ограничен установщиками пакетов и средствами сборки, а команда
        // обязана стоять в позиции команды. Благодаря этому проверка доступности средства
        // записью вида `command -v docker >/dev/null || true`, где подавление кода
        // возврата является законным приёмом, находкой не признаётся.
        Rule {
            id: "shell-ignored-failure",
            severity: Low,
            exts: SHELL_EXTS,
            matcher: Matcher::regex(
                r"(?i)(?:^|[;&|(]|\b(?:then|do|else)[ \t])[ \t]*(?:sudo[ \t]+)?(?:apt-get|apt|yum|dnf|apk|brew|npm|yarn|pnpm|pip3|pip|make|cargo|gradle|mvn|composer|bundle|go|docker|systemctl)\b[^\n]*\|\|[ \t]*(?:true|:)[ \t]*(?:#[^\n]*)?$",
            )
            .except(r"^[ \t]*#"),
            message: "Код возврата шага установки или сборки подавлен конструкцией с безусловной истиной: отказ шага не прерывает сценарий, последующие шаги выполняются над неполным результатом, а сборка объявляется успешной (CWE-390 обработка ошибки без принятия мер). Уберите подавление, установите режим немедленного прекращения работы при ошибке и обрабатывайте отказ явно.",
        },
        // ── Права записи для всех пользователей ────────────────────────────────
        // Режим доступа, разрешающий запись всем, позволяет любому локальному процессу
        // изменить содержимое файла или подменить исполняемый объект, что превращает
        // ошибку прав в путь повышения привилегий, если файл затем исполняется или
        // читается привилегированным процессом. Признаётся и числовая, и символьная
        // запись режима, поскольку они равнозначны по последствиям.
        Rule {
            id: "shell-world-writable",
            severity: Medium,
            exts: SHELL_EXTS,
            matcher: Matcher::regex(
                r"(?:^|[;&|(]|\b(?:then|do|else)[ \t])[ \t]*(?:sudo[ \t]+)?chmod\b(?:[ \t]+-[-A-Za-z0-9]+)*[ \t]+(?:0?777|a\+rwx)\b",
            )
            .except(r"^[ \t]*#"),
            message: "Файлу или каталогу выданы права записи для всех пользователей: любой локальный процесс может изменить содержимое или подменить исполняемый объект, что даёт путь повышения привилегий (CWE-732 небезопасное назначение прав на критичный ресурс; OWASP A01:2021 Broken Access Control). Выдавайте минимально необходимые права, например режим 750 для каталога и 640 для файла, и задавайте владельца явно.",
        },
    ]
}

