    /// РЕГРЕССИЯ. Тело блочного скаляра заканчивается на строке, открывающей следующий шаг,
    /// то есть на строке с дефисом после отступа. Прежде отступ и дефис распознавались так,
    /// что дефис мог быть засчитан как обычный символ содержимого: класс символов запрещал
    /// только дефис и перенос строки, поэтому при разборе отступа он поглощался частично, а
    /// оставшийся пробел проходил проверку. Из-за этого выражение из блока `with` СЛЕДУЮЩЕГО
    /// шага приписывалось телу предыдущей команды, и совершенно исправный рабочий процесс
    /// получал находку критической важности. Проверялось прогоном на образце ниже.
    #[test]
    fn выражение_соседнего_шага_к_телу_команды_не_относится() {
        let out = ci_out(
            "neighbour.yml",
            "jobs:\n  build:\n    runs-on: ubuntu-latest\n    steps:\n      - run: |\n          make build\n      - uses: actions/checkout@v4\n        with:\n          ref: ${{ github.head_ref }}\n",
        );
        assert!(
            !has_rule(&out, "ci-untrusted-input-in-run"),
            "выражение в блоке with следующего шага не является телом предыдущей команды: {:?}",
            out.findings
        );
    }

