    #[test]
    fn закрытая_группа_безопасности_и_исходящий_трафик_не_находка() {
        let rs = terraform_rules();
        let r = rule(&rs, "tf-open-security-group");
        // Исходящее правило с тем же адресом является обычной практикой и находкой быть
        // не должно, в том числе когда рядом стоит закрытый блок входящего трафика.
        assert!(
            !hits(
                r,
                "resource \"aws_security_group\" \"hardened\" {\n  ingress {\n    from_port   = 443\n    to_port     = 443\n    cidr_blocks = [\"10.0.0.0/8\"]\n  }\n  egress {\n    from_port   = 0\n    to_port     = 0\n    cidr_blocks = [\"0.0.0.0/0\"]\n  }\n}\n"
            ),
            "исходящий трафик наружу не является находкой"
        );
        assert!(
            !hits(
                r,
                "resource \"aws_security_group_rule\" \"out\" {\n  type        = \"egress\"\n  cidr_blocks = [\"0.0.0.0/0\"]\n}\n"
            ),
            "отдельное правило с направлением egress не является находкой"
        );
        assert!(
            !hits(
                r,
                "  ingress {\n    cidr_blocks = [\"192.168.10.0/24\", \"10.1.0.0/16\"]\n  }\n"
            ),
            "входящий трафик из доверенных подсетей не является находкой"
        );
    }

