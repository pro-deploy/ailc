//! Дополнительные классы инъекций и небезопасного обращения с недоверенным вводом,
//! не покрытые существующими сканерами. Модуль устроен как тонкий конфиг: таблица
//! правил поверх общего `ScanEngine`, без какой-либо новой логики обхода дерева,
//! сопоставления строк или выпуска находок.
//!
//! ЗАЧЕМ ЭТОТ МОДУЛЬ. В сканере уже закрыты шесть классов: инъекция команды
//! операционной системы, инъекция языка структурированных запросов (SQL), обход пути
//! к файлу, межсайтовое исполнение сценариев, подделка запроса со стороны сервера и
//! небезопасная десериализация. Практика показывает, что за пределами этого набора
//! остаётся ещё несколько классов, которые встречаются регулярно и приводят к тем же
//! последствиям: чтение чужих записей каталога, выполнение произвольного метода,
//! отказ в обслуживании на подобранной строке, кража сессии из хранилища браузера.
//! Здесь они добавлены отдельным сканером, чтобы каждый класс имел собственный
//! идентификатор правила, собственную важность и собственное место в отчёте.
//!
//! АНТИ-ДУБЛИРОВАНИЕ. Ни одно правило этого модуля не повторяет уже существующие
//! идентификаторы. В частности, инъекция SQL, инъекция команды оболочки, обход пути,
//! подделка запроса со стороны сервера, межсайтовое исполнение сценариев, небезопасная
//! десериализация, разбор XML с внешними сущностями, инъекция в шаблон на стороне
//! сервера, инъекция в базу без схемы, открытое перенаправление, инъекция в журнал,
//! массовое присваивание, прямая ссылка на объект, сравнение секретов за переменное
//! время, слабый генератор случайных чисел, слабая хеш-функция, подпись JWT с
//! алгоритмом none, обход пути при распаковке архива, гонка проверки и использования
//! файла, переполнение при вычислении размера выделения и разыменование пустого
//! указателя после выделения памяти закрыты в других модулях и здесь НЕ дублируются.
//! Здесь же покрыты: катастрофический возврат в регулярном выражении, загрязнение
//! прототипа, инъекция в выражение XPath, инъекция в фильтр LDAP, небезопасная
//! рефлексия, приём оповещения без проверки подписи, хранение маркера доступа в
//! локальном хранилище браузера и установка cookie сессии без атрибута SameSite.
//!
//! ПОЧЕМУ ПАТТЕРНЫ ИМЕННО ТАКИЕ. Ложное срабатывание в этом продукте дороже пропуска,
//! поскольку человек, получивший блокирующий вердикт на исправном коде, перестаёт
//! доверять вердикту вообще, и тогда обесцениваются все остальные правила разом.
//! Поэтому каждый паттерн требует ОДНОВРЕМЕННО двух вещей: реальной формы вызова
//! (имя стока со скобкой, конкретный синтаксис фильтра или выражения) и признака
//! недоверенного происхождения данных (обращение к объекту запроса, к параметрам, к
//! аргументам командной строки, либо структурная склейка строкового литерала с
//! переменной). Одного упоминания слова в комментарии или в прозе для срабатывания
//! недостаточно ни в одном правиле.
//!
//! ОТРИЦАНИЕ КАК ОГОВОРКА. Крейт `regex` намеренно не поддерживает просмотр вперёд,
//! поэтому условие «сток присутствует, а защитной меры рядом нет» напрямую регулярным
//! выражением не выражается. Там, где такое условие составляет суть класса (проверка
//! подписи оповещения, атрибут SameSite у cookie), применяется штатная обёртка
//! `Matcher::except`: основной паттерн находит форму вызова, а паттерн-исключение
//! снимает находку, если в тексте совпадения присутствует признак защиты. Оговорка
//! видит текст совпадения вместе с небольшим хвостом, а не весь файл, поэтому защитная
//! мера, вынесенная в удалённый вспомогательный модуль, оговоркой не улавливается; это
//! ограничение честно названо в комментарии соответствующего правила.
//!
//! МНОГОСТРОЧНЫЙ ОХВАТ. Обработчик оповещения и установка cookie почти всегда занимают
//! несколько физических строк, потому что форматтер переносит аргументы вызова. Для
//! этих правил применяется `Matcher::window_regex`, связывающий признаки в пределах
//! окна строк. Остальные правила остаются построчными, так как их признаки по природе
//! умещаются в одну строку.

use ailc_contracts::{Family, Severity};
use ailc_core::engines::scan::{Matcher, Rule, SOURCE_CODE};
use ailc_core::registry::Registry;

use crate::{scan_manifest, ScanCapability};

/// Расширения экосистемы JavaScript и TypeScript. Два правила этого модуля описывают
/// явления, существующие только там: цепочка прототипов принадлежит объектной модели
/// JavaScript, а локальное и сессионное хранилище суть интерфейсы браузера. Применять
/// такие правила к исходникам на Go, Java или Python бессмысленно, и сужение списка
/// расширений убирает целый пласт потенциальных ложных срабатываний ещё до матча.
const JS_TS_CODE: &[&str] = &["ts", "tsx", "js", "jsx", "mjs", "cjs"];

// ───────────────────── security.scan/injection-extra ─────────────────────

/// Классы инъекций и небезопасного обращения с вводом, дополняющие уже закрытые
/// сканером. Каждое правило требует реальной формы вызова и признака недоверенного
/// происхождения данных, а каждое сообщение несёт проверенную ссылку на запись
/// каталога слабостей CWE и, где это применимо, рубрику OWASP Top 10.
pub fn injection_extra_scan() -> ScanCapability {
    ScanCapability::new(
        scan_manifest(
            "security.scan/injection-extra",
            Family::Security,
            "Дополнительные классы инъекций и небезопасного обращения с недоверенным вводом, не покрытые прочими сканерами: катастрофический возврат в регулярном выражении из-за вложенной квантификации, загрязнение прототипа объекта, инъекция в выражение XPath, инъекция в фильтр каталога LDAP, небезопасная рефлексия по имени класса или метода, приём входящего оповещения без проверки подписи, хранение маркера доступа в локальном хранилище браузера, установка cookie сессии без атрибута SameSite. Покрытие паттерновое: правило связывает форму вызова с признаком недоверенного ввода в пределах строки или окна строк, поэтому ручной обзор остаётся желательным.",
        ),
        injection_extra_rules(),
    )
}

/// Таблица правил `security.scan/injection-extra`. Вынесена отдельной функцией по той
/// же причине, что и таблицы прочих сканеров: тест берёт конкретное правило по
/// идентификатору и проверяет его матчер на образцах, не обходя файловое дерево.
fn injection_extra_rules() -> Vec<Rule> {
    use Severity::{High, Medium};
    vec![
        // ── Катастрофический возврат в регулярном выражении ───────────────────
        //
        // Вложенная квантификация вида «(a+)+» задаёт экспоненциально много способов
        // разбить одну и ту же подстроку между внутренним и внешним квантификатором.
        // На строке, подобранной так, чтобы совпадение в итоге не состоялось, движок с
        // возвратом перебирает все разбиения, и время работы растёт экспоненциально от
        // длины входа. Одна такая проверка ввода в обработчике запроса превращается в
        // отказ в обслуживании без единого лишнего запроса.
        //
        // Паттерн требует ДВУХ признаков сразу. Во-первых, контекста регулярного
        // выражения: вызова компиляции или сопоставления в одной из распространённых
        // экосистем, либо литерала регулярного выражения JavaScript после знака
        // присваивания, открывающей скобки или запятой. Без этого условия обычная
        // арифметика вида «(a + b) * c» немедленно давала бы ложные срабатывания.
        // Во-вторых, самой вложенной квантификации: группа, содержимое которой включает
        // квантификатор «+» или «*», а сама группа снабжена квантификатором «+», «*»
        // либо «{n,}». Содержимое группы дополнительно объявлено свободным от пробелов,
        // что окончательно отделяет запись регулярного выражения от арифметики, где
        // операторы принято окружать пробелами. Группа без внутреннего квантификатора,
        // например «(abc)+», условию не удовлетворяет и находкой не является.
        //
        // Признак литерала записан ДВУМЯ ветвями по чисто технической причине. Ветвь,
        // проверяющая символ после косой черты (он не должен быть косой чертой или
        // звёздочкой, иначе это строчный либо блочный комментарий), этот символ
        // потребляет, поэтому у литерала, который начинается сразу с группы, она забирает
        // открывающую скобку, и вложенная квантификация после неё уже не находится.
        // Просмотр вперёд в крейте `regex` намеренно отсутствует, и обойтись одной ветвью
        // нельзя. Вторая ветвь описывает ровно этот случай: косая черта, необязательный
        // знак начала строки и сразу открывающая скобка группы.
        Rule {
            id: "redos-nested-quantifier",
            severity: High,
            exts: SOURCE_CODE,
            matcher: Matcher::regex(
                r#"(?:(?:\bRegExp\s*\(|\bre\.(?:compile|match|search|fullmatch|sub|subn|split|findall|finditer)\s*\(|\bPattern\.compile\s*\(|\bRegex::new\s*\(|\bregexp\.(?:MustCompile|Compile)\s*\(|\bRegexp\.new\s*\(|\bpreg_(?:match|match_all|replace|split)\s*\(|\bnew\s+Regex\s*\(|\breturn\s+/[^/*\n ]|[=(,]\s*/[^/*\n ])[^\n]{0,160}?|(?:[=(,]|\breturn)\s*/\^?)\([^()\s\n]{0,60}[+*][^()\s\n]{0,24}\)(?:[+*]|\{\d+,\s*\})"#,
            ),
            message: "Регулярное выражение с вложенной квантификацией допускает катастрофический возврат (CWE-1333, OWASP A05:2021). Подобранная строка заставит движок перебирать экспоненциально много разбиений и приведёт к отказу в обслуживании; перепишите выражение без вложенных квантификаторов, ограничьте длину проверяемого значения и применяйте движок с линейным временем работы либо тайм-аут сопоставления.",
        },
        // ── Загрязнение прототипа объекта ─────────────────────────────────────
        //
        // В объектной модели JavaScript запись в свойство с именем «__proto__» либо в
        // «constructor.prototype» изменяет не сам объект, а его прототип, то есть общий
        // для всех однотипных объектов носитель свойств. Если имя свойства приходит из
        // недоверенного ввода и не проверяется на служебные значения, атакующий одним
        // запросом задаёт свойство сразу всем объектам процесса, чем обходит проверки
        // прав, подменяет параметры вызова внешних программ и в ряде сборок доходит до
        // выполнения произвольного кода.
        //
        // Паттерн описывает три реальные формы. Первая: рекурсивное слияние объектов,
        // где вторым аргументом стоит тело, строка запроса или параметры маршрута;
        // область поиска аргумента объявлена свободной от кавычек, поэтому признак
        // недоверенного ввода не может быть засчитан из содержимого строкового литерала.
        // Вторая: присваивание в свойство по ключу, взятому прямо из объекта запроса.
        // Третья: явная запись в служебное свойство прототипа. Безопасное слияние
        // постоянных значений, как и проверка принадлежности свойства через
        // hasOwnProperty, ни одной из форм не удовлетворяет.
        Rule {
            id: "prototype-pollution",
            severity: High,
            exts: JS_TS_CODE,
            matcher: Matcher::regex(
                r#"(?:\b(?:merge|mergeWith|mergeDeep|deepMerge|deepExtend|extendDeep|defaultsDeep|extend|Object\.assign)\s*\(\s*[^;\n"'`]{0,100}?(?:req\.(?:body|query|params)|request\.(?:body|query|params)|ctx\.request\.body|\buserInput\b|\buser_input\b)|\[\s*(?:req|request)\.(?:body|query|params)[^\]\n]{0,60}\]\s*=[^=]|(?:\.__proto__|\[\s*['"]__proto__['"]\s*\]|\bconstructor\s*\.\s*prototype)\s*(?:\.[A-Za-z_$][\w$]*|\[[^\]\n]{0,60}\])?\s*=[^=])"#,
            ),
            message: "Загрязнение прототипа: значение из недоверенного ввода попадает в свойство объекта по ключу, который может оказаться служебным именем (CWE-1321, OWASP A03:2021 Injection). Запись в прототип меняет поведение всех однотипных объектов процесса и обходит проверки прав; отклоняйте ключи со служебными именами, храните словари в Map или в объекте, созданном через Object.create(null), а слияние выполняйте строго по списку разрешённых полей.",
        },
        // ── Инъекция в выражение XPath ────────────────────────────────────────
        //
        // Выражение XPath, собранное склейкой с недоверенным вводом, позволяет закрыть
        // текущий предикат и дописать собственное условие, после чего запрос возвращает
        // узлы за пределами разрешённых. Класс полностью аналогичен инъекции SQL, но
        // остаётся незамеченным, поскольку хранилищем выступает документ XML, а не база
        // данных, и штатные средства параметризации применяются реже.
        //
        // Паттерн требует стока (вычисление или выборка по выражению) и СТРУКТУРНОГО
        // признака склейки: строкового литерала, который начинается с косой черты либо
        // содержит предикат вида «[@атрибут=», и который непосредственно соединён с
        // переменной оператором конкатенации или содержит подстановку значения. Готовое
        // постоянное выражение без склейки этому условию не удовлетворяет. Оговорка
        // снимает находку, когда в строке присутствует признак экранирования или
        // приведения значения, поскольку такой код уже защищён.
        Rule {
            id: "xpath-injection",
            severity: High,
            exts: SOURCE_CODE,
            matcher: Matcher::regex(
                r#"(?i)\b(?:xpath|selectNodes|selectSingleNode|evaluate|XPathExpression|newXPath)\s*\(\s*[^;\n]{0,60}?["'](?:/{1,2}|[^\n]{0,80}?\[\s*@?[\w:.-]{1,40}\s*=)[^\n]{0,120}?(?:["']\s*[+.]|\$\{|\{[A-Za-z_])"#,
            )
            .except(r"(?i)escape|sanitiz|quoteAttr|XPathVariable|setVariable"),
            message: "Инъекция в выражение XPath: выражение собирается склейкой с недоверенным вводом (CWE-643, OWASP A03:2021 Injection). Атакующий закроет предикат и допишет собственное условие, получив узлы за пределами разрешённых; передавайте значение отдельной переменной выражения через XPathVariableResolver либо строго экранируйте кавычки и служебные символы.",
        },
        // ── Инъекция в фильтр каталога LDAP ───────────────────────────────────
        //
        // Фильтр каталога LDAP имеет скобочный синтаксис, в котором символы «(», «)»,
        // «&», «|» и «*» суть операторы. Подстановка недоверенного значения без
        // экранирования по RFC 4515 позволяет заменить условие поиска целиком, например
        // превратить проверку пары «идентификатор и пароль» в тождественно истинное
        // условие и войти под чужой учётной записью.
        //
        // Паттерн описывает две формы. Первая опирается на ОДНОЗНАЧНЫЙ структурный
        // признак: строковый литерал обрывается ровно на знаке равенства после имени
        // атрибута каталога и тут же соединяется с переменной, то есть значение
        // атрибута заведомо подставляется извне. Такая запись почти не встречается ни в
        // каком другом качестве, поэтому не нуждается в дополнительном контексте. Вторая
        // форма требует явного признака работы с каталогом (клиент, запрос поиска,
        // контекст каталога) вместе со склейкой литерала с недоверенным источником.
        // Оговорка снимает находку при наличии признака экранирования значения фильтра.
        Rule {
            id: "ldap-injection",
            severity: High,
            exts: SOURCE_CODE,
            matcher: Matcher::regex(
                r#"(?i)(?:["'][^"'\n]{0,80}\(\s*(?:[&|]\s*)?\(?\s*(?:uid|cn|sn|mail|objectclass|samaccountname|userprincipalname|memberof|givenname|displayname|ou)\s*=\s*["']\s*[+.]|(?:\bldap|\bSearchRequest\b|\bInitialDirContext\b|\bDirectorySearcher\b|\bsearch_s\b|\bsearch_ext_s\b)[^;{\n]{0,200}?["'][^"'\n]{0,120}["']\s*\+\s*(?:req\.|request\.|\bparams\b|\binput\b|\buser\b|\bargv\b|getParameter|\busername\b))"#,
            )
            .except(r"(?i)escape|sanitiz|encodeFilter"),
            message: "Инъекция в фильтр каталога LDAP: фильтр собирается склейкой с недоверенным вводом (CWE-90, OWASP A03:2021 Injection). Служебные символы скобочного синтаксиса позволяют заменить условие поиска и получить чужие записи каталога либо обойти проверку учётных данных; экранируйте значение по RFC 4515 средствами библиотеки или применяйте параметризованный запрос поиска.",
        },
        // ── Небезопасная рефлексия ────────────────────────────────────────────
        //
        // Загрузка класса, получение метода или импорт модуля по имени, пришедшему из
        // недоверенного ввода, отдаёт атакующему выбор исполняемого кода в пределах
        // всего пути классов или пути импорта. Это не абстрактная опасность: в типовом
        // приложении на пути классов всегда находится тип, конструктор или метод,
        // побочное действие которого равносильно выполнению команды.
        //
        // Паттерн требует стока рефлексии со скобкой и признака недоверенного ввода
        // в его аргументах. Область поиска аргумента объявлена свободной от кавычек,
        // и это существенно: без такого сужения безобидная строка вида
        // require('./request.js') засчитывалась бы за недоверенный источник только из-за
        // подстроки внутри литерала. Постоянное имя класса или модуля признаку не
        // удовлетворяет и находкой не является.
        Rule {
            id: "unsafe-reflection",
            severity: High,
            exts: SOURCE_CODE,
            matcher: Matcher::regex(
                r#"(?i)\b(?:Class\.forName|Type\.GetType|Activator\.CreateInstance|getattr|setattr|importlib\.import_module|__import__|getMethod|getDeclaredMethod|getConstructor|getDeclaredConstructor|require|import)\s*\(\s*[^;\n"'`]{0,80}?(?:request\.|\breq\.|\bparams\b|\bargv\b|user_input|userInput|getParameter|\$_GET|\$_POST|\$_REQUEST|\bquery\.)"#,
            ),
            message: "Небезопасная рефлексия: класс, метод или модуль выбирается по имени из недоверенного ввода (CWE-470, OWASP A03:2021 Injection). Атакующий получает выбор исполняемого кода в пределах всего пути классов или пути импорта; сопоставляйте имя со списком разрешённых значений и никогда не передавайте ввод в загрузчик напрямую.",
        },
        // ── Приём входящего оповещения без проверки подписи ───────────────────
        //
        // Обработчик входящего оповещения (вебхука) доступен из сети всем, поэтому тело
        // запроса до проверки подписи является полностью недоверенным. Обработчик,
        // который сразу разбирает полезную нагрузку и совершает по ней действия,
        // позволяет любому отправителю выдать себя за платёжную систему или систему
        // управления репозиториями и, например, подтвердить неоплаченный заказ.
        //
        // ОГРАНИЧЕНИЕ, названное честно. Условие «признака проверки нет нигде рядом»
        // регулярным выражением не выражается, так как крейт `regex` намеренно лишён
        // просмотра вперёд. Поэтому правило построено как оговорка: основной паттерн
        // требует ОДНОЗНАЧНОГО признака приёма оповещения (маршрут или имя обработчика,
        // прямо содержащие слово webhook) вместе с чтением тела запроса, а
        // паттерн-исключение снимает находку при любом упоминании подписи, кода
        // проверки подлинности сообщения, сравнения за постоянное время или заголовка
        // подписи в тексте совпадения. Отсюда два следствия. Обработчик, называющий
        // себя иначе, правилом не покрывается, что является осознанным сужением ради
        // точности. Проверка подписи, вынесенная в удалённый вспомогательный модуль и
        // не оставившая следа в пределах окна строк, оговоркой не улавливается, и такая
        // находка требует ручного подтверждения.
        Rule {
            id: "webhook-signature-unverified",
            severity: Medium,
            exts: SOURCE_CODE,
            matcher: Matcher::window_regex(
                r#"(?is)(?:(?:app|router|server|bp|blueprint)\.(?:post|put|route)\s*\(\s*["'`][^"'`\n]{0,80}webhook|@(?:app|bp|router|blueprint)\.(?:route|post)\s*\(\s*["'`][^"'`\n]{0,80}webhook|(?:def|func|function|const|let)\s+[a-z_]{0,30}webhook[a-z_]{0,30}\s*[=(]).{0,600}(?:req\.body|request\.body|request\.get_data|request\.data|request\.json|r\.Body|io(?:util)?\.ReadAll)"#,
                12,
            )
            .except(r"(?i)hmac|verif|signature|constructEvent|compare_digest|timingSafeEqual|x-hub|x-signature|checksum|digest"),
            message: "Обработчик входящего оповещения (вебхука) разбирает тело запроса, и признаков проверки подписи рядом не обнаружено (CWE-345, OWASP A08:2021). Отправителем может оказаться кто угодно, поэтому действия по такой нагрузке совершаются от лица постороннего; вычисляйте код проверки подлинности сообщения от СЫРОГО тела общим секретом и сравнивайте его с заголовком подписи функцией постоянного времени до любого разбора.",
        },
        // ── Маркер доступа в локальном хранилище браузера ─────────────────────
        //
        // Локальное и сессионное хранилище браузера доступны любому сценарию, который
        // исполняется на странице, и не защищены ни признаком HttpOnly, ни привязкой к
        // источнику запроса. Маркер доступа или обновления, положенный туда, читается
        // одной строкой стороннего сценария, поэтому единственная ошибка вставки
        // разметки или скомпрометированная зависимость сборки превращаются в кражу
        // сессии, переживающую смену пароля до истечения срока действия маркера.
        //
        // Паттерн требует ЗАПИСИ (метод сохранения либо присваивание в свойство
        // хранилища) и содержательного имени ключа из перечня обозначений секрета.
        // Чтение из хранилища и запись пользовательских настроек, например темы
        // оформления, признаку не удовлетворяют и находкой не являются.
        Rule {
            id: "token-in-localstorage",
            severity: Medium,
            exts: JS_TS_CODE,
            matcher: Matcher::regex(
                r#"(?i)\b(?:local|session)Storage\s*(?:\.\s*setItem\s*\(\s*["'`][^"'`\n]{0,40}(?:token|jwt|bearer|credential|api[_-]?key|secret|password|authorization|session[_-]?id)|\[\s*["'`][^"'`\n]{0,40}(?:token|jwt|bearer|credential|api[_-]?key|secret|authorization)[^"'`\n]{0,40}["'`]\s*\]\s*=[^=]|\.\s*(?:token|jwt|accessToken|refreshToken|idToken|access_token|refresh_token|id_token|apiKey|api_key|authToken|auth_token|bearer|credentials)\s*=[^=])"#,
            ),
            message: "Маркер доступа или обновления сохраняется в локальном либо сессионном хранилище браузера (CWE-922, OWASP A01:2021). Это хранилище читает любой исполняемый на странице сценарий, поэтому одна ошибка вставки разметки или скомпрометированная зависимость сборки превращается в кражу сессии; храните маркер в cookie с признаками HttpOnly, Secure и SameSite либо только в памяти вкладки.",
        },
        // ── Cookie сессии без атрибута SameSite ───────────────────────────────
        //
        // Атрибут SameSite указывает браузеру, отправлять ли cookie при запросе,
        // инициированном сторонним сайтом. Без него cookie сессии прикрепляется к
        // межсайтовому запросу, и форма, размещённая на чужой странице, действует от
        // имени вошедшего пользователя. Значения по умолчанию у браузеров различаются и
        // меняются между версиями, поэтому полагаться на них нельзя: атрибут следует
        // задавать явно. Правило намеренно не пересекается с уже существующим правилом
        // о признаках Secure и HttpOnly: там речь о выключенных признаках, здесь об
        // отсутствующем атрибуте.
        //
        // Реализовано оговоркой по той же причине, что и правило о подписи оповещения:
        // отрицание регулярным выражением невыразимо. Основной паттерн требует вызова
        // установки cookie, имя которой содержит обозначение сессии или маркера, вместе
        // с полным списком её аргументов до закрывающей скобки, а паттерн-исключение
        // снимает находку при наличии атрибута в тексте совпадения. Ограничение состоит
        // в том, что атрибут, заданный один раз общей настройкой платформы, в тексте
        // вызова не виден, и такая находка требует ручного подтверждения.
        Rule {
            id: "cookie-without-samesite",
            severity: Medium,
            exts: SOURCE_CODE,
            matcher: Matcher::window_regex(
                r#"(?is)(?:\.cookie\s*\(|\bset[-_]?cookie\s*\(|\bnew\s+(?:Http)?Cookie\s*\(|\bcookies\.set\s*\()\s*["'`][^"'`\n]{0,40}(?:sess|sid|token|jwt|auth|login|remember|csrf)[^"'`\n]{0,40}["'`][^;]{0,200}\)"#,
                4,
            )
            .except(r"(?i)same[_-]?site"),
            message: "Cookie сессии устанавливается без атрибута SameSite (CWE-1275, OWASP A05:2021). Без него браузер прикрепит cookie к запросу, инициированному сторонним сайтом, что открывает подделку межсайтового запроса; задайте SameSite=Lax или SameSite=Strict, а для действительно межсайтовых сценариев SameSite=None совместно с признаком Secure.",
        },
    ]
}

