    /// Найти правило по идентификатору в таблице.
    fn rule<'a>(rules: &'a [Rule], id: &str) -> &'a Rule {
        rules
            .iter()
            .find(|r| r.id == id)
            .unwrap_or_else(|| panic!("правило {id} должно существовать"))
    }

    /// Истина, если матчер правила срабатывает на тексте. Для построчных матчеров текст
    /// проверяется построчно, для оконных и файловых берётся весь фрагмент сразу, как это
    /// делает движок по окну либо по файлу.
    fn hits(r: &Rule, text: &str) -> bool {
        if r.matcher.is_multiline() {
            r.matcher.is_match(text)
        } else {
            text.lines().any(|l| r.matcher.is_match(l))
        }
    }

