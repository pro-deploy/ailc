/// Человекочитаемый вердикт — то, что увидит не-эксперт в IDE.
pub fn format_ledger(l: &QualityLedger) -> String {
    let mut s = String::new();
    s.push_str(&l.headline);
    s.push('\n');
    let t = ailc_core::i18n::t;
    s.push_str(&format!("{}: {}\n", t("Проект", "Project"), l.project));
    s.push_str(&format!(
        "{}: {}\n",
        t("Карта кода", "Code map"),
        l.map_summary
    ));
    s.push_str(&format!(
        "{} «{}»\n",
        t("Governance: политика", "Governance: policy"),
        l.policy_name
    ));
    s.push_str(&format!(
        "{}: {} · {}: {} ({} {} / {} {}) · {} {:.1}/100\n",
        t("Проверок", "Checks"),
        l.checks_run,
        t("находок", "findings"),
        l.findings_total,
        t("блокеров", "blocking"),
        l.blocking,
        t("предупреждений", "warnings"),
        l.warning,
        t("качество", "quality"),
        l.score
    ));
    s.push_str(&format!(
        "{}: {:.0}/100",
        t("Тщательность (Rigor)", "Rigor"),
        l.rigor
    ));
    if l.refuted > 0 {
        s.push_str(&format!(
            " · {}: {}",
            t("verify отсеял ложных", "verify refuted false"),
            l.refuted
        ));
    }
    s.push('\n');
    if !l.checks.is_empty() {
        s.push_str(&format!(
            "{}: {}\n",
            t("Выполнено", "Ran"),
            l.checks.join(", ")
        ));
    }
    for (id, reason) in &l.checks_skipped {
        s.push_str(&format!("⚠ {} {id}: {reason}\n", t("пропущено", "skipped")));
    }
    for a in &l.artifacts {
        s.push_str(&format!(
            "📄 {}: {a}\n",
            t("создано/обновлено", "created/updated")
        ));
    }
    if !l.open_decisions.is_empty() {
        s.push_str(&format!(
            "\n{}:\n",
            t("Нужно твоё решение", "Your decision needed")
        ));
        for d in &l.open_decisions {
            s.push_str(&format!(" • {d}\n"));
        }
    }
    if !l.advisories.is_empty() {
        s.push_str(&format!(
            "\n📋 {}:\n",
            t("Советы (не блокируют сдачу)", "Advisories (non-blocking)")
        ));
        for a in &l.advisories {
            s.push_str(&format!(" • {a}\n"));
        }
    }
    // Журнал адаптивной петли агента — чтобы человек ВИДЕЛ, что план был построен,
    // что выполнено/довызвано/починено (а не «нейросеть один раз что-то дёрнула»).
    if !l.rounds.is_empty() {
        s.push_str(&format!("\n🔁 {}:\n", t("Раунды агента", "Agent rounds")));
        for r in &l.rounds {
            s.push_str(&format!(" • {r}\n"));
        }
    }
    s
}

