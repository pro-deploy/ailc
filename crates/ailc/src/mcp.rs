    /// Отмена, пришедшая во время исполнения, поднимает флаг на выполняющемся вызове, и этот
    /// флаг доживает до формирования ответа: именно по нему вместо результата отправляется
    /// корректная ошибка «запрос отменён».
    #[test]
    fn отмена_поднимает_флаг_на_выполняющемся_вызове() {
        let c = Cancellation::default();
        assert!(
            !c.begin(&json!(1)),
            "свежий запрос стартует без признака отмены"
        );
        assert!(!c.current_cancelled(), "флаг ещё опущен");

        assert!(
            c.cancel(&json!(1)),
            "отмена попала именно в выполняющийся вызов"
        );
        assert!(
            c.current_cancelled(),
            "флаг отмены поднят и виден длительным ожиданиям внутри вызова"
        );
        assert!(c.finish(), "на момент завершения работы флаг отмены поднят");
        assert!(
            !c.current_cancelled(),
            "после завершения флаг снят, следующий вызов не наследует чужую отмену"
        );
    }

    /// Отмена запроса, который ещё ждёт в очереди за долгим вызовом, ловится ДО старта:
    /// работа не выполняется вовсе. Это и есть главный практический выигрыш отмены, ведь
    /// сквозной остановки внутри движков нет.
    #[test]
    fn отмена_в_очереди_ловится_до_начала_исполнения() {
        let c = Cancellation::default();
        assert!(
            !c.cancel(&json!(42)),
            "выполняющегося вызова нет, отмена относится к очереди"
        );
        assert!(
            c.begin(&json!(42)),
            "при постановке на исполнение отмена обнаружена, работу выполнять не нужно"
        );
        c.finish();
    }

    /// Отмена чужого запроса не трогает выполняющийся: перепутать их нельзя, иначе клиент
    /// терял бы результат работы, которую не отменял. Идентификатор-число и
    /// идентификатор-строка в JSON-RPC различны, и учёт отмены обязан это различать.
    #[test]
    fn отмена_чужого_запроса_не_трогает_выполняющийся() {
        let c = Cancellation::default();
        c.begin(&json!(1));
        assert!(!c.cancel(&json!(2)), "отменён другой запрос");
        assert!(
            !c.cancel(&json!("1")),
            "строковый идентификатор «1» это не число 1"
        );
        assert!(
            !c.current_cancelled(),
            "флаг выполняющегося вызова остался опущен"
        );
        assert!(!c.finish(), "ответом станет обычный результат работы");
    }

    /// Память об отменах ограничена: уведомления приходят от клиента без всякого счёта, и
    /// неограниченный список рос бы весь сеанс.
    #[test]
    fn память_об_отменах_ограничена() {
        let c = Cancellation::default();
        for i in 0..(MAX_CANCELLED_REMEMBERED as i64 + 50) {
            c.cancel(&json!(i));
        }
        assert_eq!(
            c.lock().recent.len(),
            MAX_CANCELLED_REMEMBERED,
            "длина очереди отменённых идентификаторов не растёт сверх предела"
        );
        assert!(
            c.begin(&json!(MAX_CANCELLED_REMEMBERED as i64 + 49)),
            "самая свежая отмена помнится"
        );
        c.finish();
        assert!(
            !c.begin(&json!(0)),
            "самая старая отмена вытеснена, и это осознанный размен"
        );
        c.finish();
    }

