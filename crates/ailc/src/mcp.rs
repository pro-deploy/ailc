//! Минимальный MCP-сервер поверх stdio (newline-delimited JSON-RPC 2.0).
//!
//! Двунаправленный: помимо ответов клиенту умеет САМ запросить у клиента LLM через
//! `sampling/createMessage` (для E4 LlmPlanner). `Session` реализует трейт ядра
//! `Sampler`, поэтому ядро ничего не знает о транспорте. Наружу — один front-door
//! инструмент `plan`.
//!
//! # Устройство обслуживания: поток чтения и рабочий поток
//!
//! Прежде цикл обслуживания был строго последовательным: единственный поток читал кадр,
//! обрабатывал его и только затем возвращался к чтению. Из этого следовали два тяжёлых
//! последствия. Во-первых, долгий вызов инструмента (`sarif` либо `plan` на большом дереве
//! занимает десятки секунд и вдобавок запускает внешние тесты) на всё это время переставал
//! читать стандартный ввод, поэтому проверка живости `ping` оставалась без ответа и клиент
//! среды разработки разрывал соединение по своему таймауту. Во-вторых, уведомление
//! `notifications/cancelled` физически невозможно было даже заметить, то есть пути отмены не
//! существовало вовсе.
//!
//! Поэтому чтение вынесено в ОТДЕЛЬНЫЙ поток, а обслуживание разделено на два класса.
//! Быстрые методы (рукопожатие, перечисление инструментов и промптов, `ping`, уведомления)
//! обслуживаются НЕМЕДЛЕННО прямо в потоке чтения: они не трогают реестр возможностей, не
//! ходят в файловую систему проекта и завершаются за микросекунды. Долгим считается ровно
//! один метод, `tools/call`: он передаётся по очереди рабочему потоку, который выполняет
//! такие вызовы ПОСЛЕДОВАТЕЛЬНО, как и раньше.
//!
//! Последовательность вызовов инструментов сохранена намеренно, а не по недосмотру. Реестр
//! возможностей и движки рассчитаны на единственного вызывающего, вызовы мутируют файлы
//! проверяемого проекта (генераторы, автофикс, служебный каталог `.ailc/`), а трейт
//! `Sampler` требует `&mut self`. Параллельное исполнение самих инструментов потребовало бы
//! правок в других крейтах (внешние границы задачи это запрещают) и породило бы гонки за
//! рабочее дерево. Выигрыш же достигается полностью: ввод читается всегда, `ping` отвечает
//! мгновенно, отмена доходит.
//!
//! Ответ клиента на серверный запрос `sampling/createMessage` доходит до ожидающего вызова
//! так. В JSON-RPC ответ отличается от запроса отсутствием поля `method`, а единственная
//! сторона, которая шлёт запросы клиенту, это сам сервер. Значит любой кадр без `method`
//! есть ответ на наш запрос: поток чтения перенаправляет такие кадры по каналу рабочему
//! потоку, где `Sampler::sample` ждёт кадр со своим идентификатором. Тем самым sampling
//! продолжает работать, хотя стандартным вводом владеет уже другой поток.
//!
//! Стандартный вывод остаётся транспортом JSON-RPC и теперь имеет ДВУХ писателей, поэтому
//! запись кадра выполняется под общим замком ([`Outbox`]): без него кадры двух потоков
//! перемешались бы посреди строки и клиент разорвал бы соединение.

