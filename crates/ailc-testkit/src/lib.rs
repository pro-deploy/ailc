//! Общая оснастка тестов: временное рабочее дерево с гарантированной уборкой.
//!
//! ПРИЧИНА СУЩЕСТВОВАНИЯ. В двадцати трёх файлах тестов повторялась одна и та же связка из
//! счётчика `static CNT`, функции `tmp()`, собирающей путь во временном каталоге, и функции
//! `write()`, записывающей файл фикстуры. Дублирование само по себе неприятно, но главный
//! вред был не в нём, а в общем для всех копий дефекте: созданный каталог не убирался НИКОГДА.
//! Каждая копия удаляла лишь каталог с тем же порядковым номером ПЕРЕД созданием нового, а
//! номер зависел от идентификатора процесса, который у каждого прогона свой. Последствие
//! измерено: во временном каталоге машины разработчика накопилось 105 276 каталогов с
//! префиксом `ailc-`. Ни один тест при этом не падал, поэтому дефект был невидим.
//!
//! Уборка здесь построена на разрушении объекта (`Drop`), а не на вызове в конце теста. Это
//! существенно: тест, завершившийся паникой (а именно так завершается ПРОВАЛИВШИЙСЯ тест),
//! до заключительной строки не доходит, и всякая уборка, записанная в теле теста, при
//! падении не выполняется. Раскрутка стека же вызывает `Drop` в любом случае, поэтому
//! каталог убирается и при успехе, и при провале.

use std::path::{Path, PathBuf};
use std::sync::atomic::{AtomicU64, Ordering};

/// Общий счётчик, дающий различие имён внутри одного процесса.
static CNT: AtomicU64 = AtomicU64::new(0);

/// Префикс имён временных каталогов, по которому они опознаются как наши.
const PREFIX: &str = "ailc-";

/// Временное рабочее дерево теста, убирающее себя при разрушении.
///
/// Путь строится из префикса, метки вызывающего, идентификатора процесса и общего счётчика,
/// поэтому он различен и для параллельных тестов внутри одного процесса, и для одновременно
/// идущих прогонов разных наборов тестов.
pub struct TempTree {
    path: PathBuf,
}

impl TempTree {
    /// Создать пустое временное дерево. Метка попадает в имя каталога и нужна лишь человеку,
    /// разбирающему остаток после аварийного завершения процесса.
    pub fn new(tag: &str) -> TempTree {
        let n = CNT.fetch_add(1, Ordering::SeqCst);
        let path = std::env::temp_dir().join(format!("{PREFIX}{tag}-{}-{n}", std::process::id()));
        let _ = std::fs::remove_dir_all(&path);
        std::fs::create_dir_all(&path)
            .unwrap_or_else(|e| panic!("временное дерево {}: {e}", path.display()));
        TempTree { path }
    }

    /// Путь к корню дерева.
    pub fn path(&self) -> &Path {
        &self.path
    }

    /// Записать файл по относительному пути, создав промежуточные каталоги.
    /// Возвращает полный путь к записанному файлу.
    pub fn write(&self, rel: &str, content: &str) -> PathBuf {
        let p = self.path.join(rel);
        if let Some(parent) = p.parent() {
            std::fs::create_dir_all(parent)
                .unwrap_or_else(|e| panic!("каталог {}: {e}", parent.display()));
        }
        std::fs::write(&p, content).unwrap_or_else(|e| panic!("файл {}: {e}", p.display()));
        p
    }

    /// Контекст проверки с корнем в этом дереве.
    pub fn ctx(&self) -> ailc_contracts::Ctx {
        ailc_contracts::Ctx::new(
            self.path
                .to_str()
                .expect("путь временного дерева выразим в UTF-8"),
        )
    }
}

impl AsRef<Path> for TempTree {
    fn as_ref(&self) -> &Path {
        &self.path
    }
}

impl Drop for TempTree {
    fn drop(&mut self) {
        // Неудача уборки не имеет права превращаться в панику: паника внутри `Drop` во время
        // раскрутки после уже случившегося провала теста завершает процесс целиком и прячет
        // подлинную причину провала за посторонним сообщением.
        let _ = std::fs::remove_dir_all(&self.path);
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Дерево существует, пока живёт объект, и исчезает вместе с ним.
    #[test]
    fn дерево_убирается_при_разрушении() {
        let path;
        {
            let t = TempTree::new("проверка");
            path = t.path().to_path_buf();
            t.write("a/b.txt", "содержимое");
            assert!(path.join("a/b.txt").is_file(), "файл записан");
        }
        assert!(!path.exists(), "дерево убрано вместе с объектом");
    }

    /// Уборка происходит и тогда, когда тест завершился ПАНИКОЙ, то есть провалился. Ради
    /// этого свойства уборка и вынесена в `Drop`: строка в конце тела теста при панике не
    /// исполняется, и прежняя оснастка именно поэтому оставляла каталоги навсегда.
    #[test]
    fn дерево_убирается_и_после_паники() {
        let path = std::sync::Arc::new(std::sync::Mutex::new(PathBuf::new()));
        let сообщить = std::sync::Arc::clone(&path);
        let исход = std::panic::catch_unwind(move || {
            let t = TempTree::new("паника");
            *сообщить.lock().unwrap() = t.path().to_path_buf();
            t.write("x.txt", "содержимое");
            panic!("тест провалился");
        });
        assert!(исход.is_err(), "образец обязан был запаниковать");
        let p = path.lock().unwrap().clone();
        assert!(!p.exists(), "дерево убрано и после паники: {}", p.display());
    }

    /// Имена различны, иначе параллельные тесты вычищали бы дерево друг у друга.
    #[test]
    fn имена_деревьев_различны() {
        let a = TempTree::new("одна-метка");
        let b = TempTree::new("одна-метка");
        assert_ne!(a.path(), b.path());
    }
}
