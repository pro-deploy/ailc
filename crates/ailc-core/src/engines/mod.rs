//! Переиспользуемые движки. Инструмент здесь является тонкой настройкой над движком, поэтому
//! логика обхода, запуска, разбора и вынесения вердикта не дублируется по инструментам.
//!
//! Реализованы и перечислены ниже все движки, объявленные в этом модуле. Прежний текст
//! заголовка обещал девять движков, из которых называл реализованными три, а остальные
//! относил к будущему; к настоящему времени объявлено шестнадцать модулей, и почти все
//! «будущие» давно существуют. Расхождение заголовка с содержимым каталога опаснее, чем
//! отсутствие заголовка: читающий делает вывод о зрелости подсистемы по обещанию, а не по
//! коду.
//!
//! `index` строит детерминированный лексический индекс (обратный индекс и ранжирование
//! BM25). `walk` обходит дерево с учётом режима обхода. `scan` применяет правила к тексту и
//! выдаёт находки. `codeintel` извлекает символы, опираясь на разбор tree-sitter и на
//! регулярные выражения как запасной путь. `sast` ведёт анализ потока заражения по дереву
//! разбора. `surface` описывает публичную поверхность, `apidoc` сопоставляет её с
//! документацией. `runner` запускает внешние инструменты с пределом времени и дренажом
//! вывода. `osv` сверяет зависимости со снимком базы уязвимостей. `metric` считает метрики
//! размера и сложности. `gate` сводит находки в детерминированный вердикт. `store` пишет
//! состояние атомарно. `generator`, `docgen` и `diagram` выпускают документы и схемы
//! идемпотентно. `cli` разбирает справку командных интерфейсов.

