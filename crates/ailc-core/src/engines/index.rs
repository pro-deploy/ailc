//! E0 Index: детерминированный лексический индекс исходников проекта.
//!
//! Место этого движка в перечне девяти движков ранее занимала встроенная модель
//! статических эмбеддингов, вшитая в бинарь. Модель была изъята из поставки, чтобы
//! исполняемый файл не раздувался весами, и после изъятия перечень движков обещал
//! возможность, которой в продукте не существовало. Настоящий модуль закрывает этот
//! разрыв честным способом: вместо векторного приближения он строит обратный индекс
//! терминов и оценивает релевантность классической формулой BM25. Нейронная сеть не
//! применяется, внешние службы не вызываются, внешнее состояние не читается и не
//! записывается, реализация опирается только на стандартную библиотеку.
//!
//! Отказ от эмбеддингов означает отказ от семантической близости: запрос «авторизация»
//! не найдёт файл, в котором написано только «login». Взамен получены свойства, которые
//! для инструмента с детерминированным вердиктом важнее приблизительной семантики:
//! результат воспроизводим байт в байт, объясним (видно, какие именно термины запроса
//! совпали), не зависит от версии модели и не требует ни мегабайтов весов, ни прогрева.
//!
//! Индекс строится в памяти на время одного вызова и никуда не сохраняется. Такое
//! решение принято сознательно: сохранённый индекс пришлось бы инвалидировать при каждой
//! правке дерева, а несвежий индекс молча выдавал бы устаревшие ответы, что прямо
//! противоречит требованию отсутствия молчаливых расхождений.

use super::codeintel::{lang_for_ext, read_source};
use super::walk::{ext_of, is_test_path, walk};
use ailc_contracts::{Ctx, Result, RunInput};
use std::collections::{BTreeMap, BTreeSet};

/// Параметр насыщения частоты термина в формуле BM25.
///
/// Значение 1.2 взято из работ Робертсона, Спарк Джонс и соавторов по поисковой системе
/// Okapi (конференции TREC начала 1990-х годов), где оно было подобрано опытным путём и
/// с тех пор служит отраслевым значением по умолчанию: те же 1.2 применяет, в частности,
/// библиотека Apache Lucene. Смысл параметра состоит в скорости насыщения: чем он меньше,
/// тем быстрее дополнительные вхождения одного и того же термина перестают повышать
/// оценку, поэтому файл, в котором слово встречается сто раз, не получает стократного
/// преимущества над файлом, где оно встречается десять раз.
const BM25_K1: f64 = 1.2;

/// Параметр учёта длины документа в формуле BM25.
///
/// Значение 0.75 происходит из того же источника, что и [`BM25_K1`], и также является
/// общепринятым значением по умолчанию. Смысл параметра состоит в степени поправки на
/// длину: при нулевом значении длина документа не учитывается вовсе и длинные файлы
/// получают несправедливое преимущество просто потому, что содержат больше слов; при
/// единичном значении поправка на длину применяется полностью; значение 0.75 является
/// промежуточным и на практике даёт устойчивый компромисс.
const BM25_B: f64 = 0.75;

/// Предельное число РАЗЛИЧНЫХ терминов, которые индексируются от одного файла.
///
/// Предел объявлен явно и заявлен как честная граница охвата, а не как молчаливое
/// усечение: файл, у которого различных терминов оказалось больше, перечисляется по имени
/// в [`LexicalIndex::truncated_files`], поэтому человек всегда может увидеть, какие именно
/// документы проиндексированы не полностью. Величина выбрана с запасом относительно
/// реального исходного кода: файл рукописного кода почти никогда не содержит и тысячи
/// различных слов, тогда как превышение указывает на сгенерированный или похожий на
/// данные файл (таблица соответствий, дамп, словарь), у которого редкие термины
/// поискового смысла не несут.
pub const MAX_TERMS_PER_FILE: usize = 4_000;

/// Минимальная длина термина в символах. Односимвольные остатки разбора (счётчики циклов,
/// служебные суффиксы, одиночные буквы аббревиатур) поисковой ценности не имеют, зато
/// раздувают обратный индекс и совпадают почти со всем деревом.
const MIN_TERM_CHARS: usize = 2;

/// Один результат поиска по индексу.
#[derive(Debug, Clone)]
pub struct Hit {
    /// Путь файла относительно корня проекта, с прямыми косыми чертами как разделителями.
    pub file: String,
    /// Оценка релевантности по формуле BM25. Величина сопоставима только внутри одной
    /// выдачи по одному запросу и не является вероятностью или процентом.
    pub score: f64,
    /// Термины запроса, которые действительно встретились в этом файле, в лексикографическом
    /// порядке. Поле существует ради объяснимости выдачи: по нему видно, за что именно файл
    /// получил оценку, и отличается ли полное совпадение запроса от частичного.
    pub matched: Vec<String>,
}

/// Обратный индекс терминов по дереву исходников вместе со сведениями, необходимыми
/// формуле BM25 (частоты, длины документов, средняя длина документа).
///
/// Все внутренние коллекции упорядоченные. Это не стилистическое предпочтение, а условие
/// воспроизводимости: при обходе неупорядоченной хеш-таблицы порядок перебора зависит от
/// затравки хеширования, из-за чего документы с одинаковой оценкой выстраивались бы в
/// разном порядке от прогона к прогону, а выдача перестала бы быть детерминированной.
pub struct LexicalIndex {
    /// Обратный индекс: термин, затем перечень содержащих его файлов с частотой термина
    /// в каждом файле.
    postings: BTreeMap<String, BTreeMap<String, u32>>,
    /// Длина каждого документа, выраженная числом учтённых вхождений терминов. Считается
    /// уже ПОСЛЕ применения предела [`MAX_TERMS_PER_FILE`], чтобы нормировка по длине
    /// соответствовала тому, что действительно доступно поиску, а не тому, что было в файле.
    lengths: BTreeMap<String, u32>,
    /// Средняя длина документа по индексу. Хранится готовой величиной, поскольку входит в
    /// оценку каждого документа и пересчитывать её на каждый запрос незачем.
    avg_len: f64,
    /// Файлы, у которых число различных терминов превысило [`MAX_TERMS_PER_FILE`] и потому
    /// проиндексированные не полностью.
    truncated: BTreeSet<String>,
}

pub struct IndexEngine;

impl IndexEngine {
    /// Построить лексический индекс по дереву исходников (либо по подпути `input.target`).
    ///
    /// Тестовые файлы в индекс не попадают: индекс описывает продукт, а фикстуры и
    /// проверочные данные к составу продукта не относятся, при этом они изобилуют
    /// повторяющимися словами и, попав в индекс, вытесняли бы прикладной код из верхних
    /// строк выдачи. Отсев выполняется функцией [`is_test_path`], то есть тем же критерием,
    /// которым пользуются сканеры, поэтому представление о тестовом файле в проекте
    /// остаётся единым.
    pub fn build(ctx: &Ctx, input: &RunInput) -> Result<LexicalIndex> {
        // Базовый путь берётся через `Ctx::base`, поскольку там же выполняется проверка
        // того, что `target` от клиента не выводит обход за корень проекта.
        let base = ctx.base(input)?;
        let root = ctx.root.clone();

        let mut postings: BTreeMap<String, BTreeMap<String, u32>> = BTreeMap::new();
        let mut lengths: BTreeMap<String, u32> = BTreeMap::new();
        let mut truncated: BTreeSet<String> = BTreeSet::new();

        walk(&base, &mut |path| {
            // Расширение приводится к нижнему регистру: на файловых системах, различающих
            // регистр, встречается запись вида `README.MD`, и без приведения такой файл
            // молча выпадал бы из охвата.
            let ext = ext_of(path).to_ascii_lowercase();
            if !is_indexable_ext(&ext) {
                return;
            }

            // Путь нормализуется к прямым косым чертам, чтобы выдача на Windows и на
            // Unix-подобных системах совпадала посимвольно.
            let rel = path
                .strip_prefix(&root)
                .unwrap_or(path)
                .to_string_lossy()
                .replace('\\', "/");
            if is_test_path(&rel) {
                return;
            }

            // Чтение идёт через общий устойчивый к кодировке читатель: он снимает метку
            // порядка байтов, не падает на содержимом вне UTF-8 и нормализует переводы
            // строк. Отказ ввода-вывода исключает ОДИН файл, а не построение индекса.
            let content = match read_source(path) {
                Some(c) => c,
                None => return,
            };

            let mut freq: BTreeMap<String, u32> = BTreeMap::new();
            for term in tokenize(&content) {
                let counter = freq.entry(term).or_insert(0);
                *counter = counter.saturating_add(1);
            }
            // Файл без единого пригодного термина документом не является: он лишь испортил
            // бы среднюю длину документа, ничего не добавив к поиску.
            if freq.is_empty() {
                return;
            }
            if freq.len() > MAX_TERMS_PER_FILE {
                freq = keep_most_frequent(freq, MAX_TERMS_PER_FILE);
                truncated.insert(rel.clone());
            }

            let len = freq.values().fold(0u32, |acc, n| acc.saturating_add(*n));
            lengths.insert(rel.clone(), len);
            for (term, n) in freq {
                postings.entry(term).or_default().insert(rel.clone(), n);
            }
        })?;

        // Сумма считается в 64 разрядах: у крупного дерева суммарное число вхождений
        // способно превысить разрядность отдельного счётчика длины.
        let total: u64 = lengths.values().map(|v| u64::from(*v)).sum();
        let avg_len = if lengths.is_empty() {
            0.0
        } else {
            total as f64 / lengths.len() as f64
        };

        Ok(LexicalIndex {
            postings,
            lengths,
            avg_len,
            truncated,
        })
    }
}

impl LexicalIndex {
    /// Число различных терминов индекса. Служит для сводки: по этой величине видно,
    /// насколько богат словарь проекта и не выродился ли индекс до нескольких слов.
    pub fn terms(&self) -> usize {
        self.postings.len()
    }

    /// Число проиндексированных документов (файлов). Служит для сводки и, вместе с
    /// [`LexicalIndex::truncated_files`], позволяет судить о полноте охвата.
    pub fn documents(&self) -> usize {
        self.lengths.len()
    }

    /// Файлы, проиндексированные не полностью из-за предела [`MAX_TERMS_PER_FILE`].
    /// Перечень возвращается поимённо, поскольку обезличенное число не позволило бы
    /// понять, какая именно часть дерева представлена в индексе частично.
    pub fn truncated_files(&self) -> &BTreeSet<String> {
        &self.truncated
    }

    /// Наиболее релевантные запросу документы, не более `limit` записей.
    ///
    /// Запрос токенизируется теми же правилами, что и содержимое файлов, поэтому запрос
    /// `parseUserName` находит файл со словами `parse`, `user` и `name` независимо от того,
    /// в каком регистре и с какими разделителями они записаны в исходнике. Термины запроса
    /// приводятся к упорядоченному множеству: повтор слова в запросе не должен удваивать
    /// вклад этого слова в оценку, иначе релевантность зависела бы от способа набора
    /// запроса, а не от содержимого файлов.
    ///
    /// Порядок выдачи полностью определён: сначала по убыванию оценки, а при равных
    /// оценках по возрастанию имени файла. Разрешение равенства по имени обязательно,
    /// поскольку у совпадающих оценок нет иного естественного порядка, и без такого
    /// правила выдача менялась бы между прогонами.
    pub fn search(&self, query: &str, limit: usize) -> Vec<Hit> {
        // Пустой индекс, нулевой предел или запрос без пригодных терминов дают ПУСТУЮ
        // выдачу, а не выдачу произвольных файлов: инструмент не должен подменять
        // отсутствие ответа правдоподобным перечнем.
        if limit == 0 || self.lengths.is_empty() {
            return Vec::new();
        }
        let terms: BTreeSet<String> = tokenize(query).into_iter().collect();
        if terms.is_empty() {
            return Vec::new();
        }

        let docs_total = self.lengths.len() as f64;
        // Средняя длина заведомо положительна для непустого индекса (каждый документ имеет
        // хотя бы одно вхождение), но подстраховка от деления на ноль оставлена явно.
        let avg_len = if self.avg_len > 0.0 {
            self.avg_len
        } else {
            1.0
        };

        let mut acc: BTreeMap<&String, (f64, BTreeSet<String>)> = BTreeMap::new();
        for term in &terms {
            let Some(docs) = self.postings.get(term) else {
                continue;
            };
            let df = docs.len() as f64;
            // Обратная документная частота в сглаженном виде Робертсона и Спарк Джонс с
            // добавлением единицы под логарифмом. Добавление единицы принципиально: в
            // несглаженной записи термин, встречающийся более чем в половине документов,
            // получает ОТРИЦАТЕЛЬНЫЙ вес, и документ, содержащий такой термин, оказывался
            // бы ниже документа, не содержащего его вовсе, что противоречит здравому
            // смыслу поиска. В приведённой форме вес всегда положителен.
            let idf = ((docs_total - df + 0.5) / (df + 0.5) + 1.0).ln();

            for (file, tf) in docs {
                let doc_len = f64::from(self.lengths.get(file).copied().unwrap_or(0));
                let tf = f64::from(*tf);
                // Знаменатель BM25: частота термина, насыщенная параметром k1 и поправленная
                // на отношение длины документа к средней длине с весом b.
                let norm = BM25_K1 * (1.0 - BM25_B + BM25_B * (doc_len / avg_len));
                let part = idf * (tf * (BM25_K1 + 1.0)) / (tf + norm);

                let slot = acc.entry(file).or_insert((0.0, BTreeSet::new()));
                slot.0 += part;
                slot.1.insert(term.clone());
            }
        }

        let mut hits: Vec<Hit> = acc
            .into_iter()
            .map(|(file, (score, matched))| Hit {
                file: file.clone(),
                score,
                matched: matched.into_iter().collect(),
            })
            .collect();
        hits.sort_by(|a, b| {
            b.score
                .partial_cmp(&a.score)
                // Оценки конечны по построению, поэтому несравнимость означала бы
                // невозможное состояние; трактуем её как равенство, которое затем
                // разрешается по имени файла, вместо прекращения работы.
                .unwrap_or(std::cmp::Ordering::Equal)
                .then_with(|| a.file.cmp(&b.file))
        });
        hits.truncate(limit);
        hits
    }
}

/// Файл подлежит индексации по расширению.
///
/// Индексируются, во-первых, файлы известных языков программирования (признаком служит
/// то, что [`lang_for_ext`] опознал язык и не вернул `text`), поскольку именно по коду и
/// ведётся поиск. Во-вторых, индексируется разметка Markdown: описание проекта, замечания
/// по решениям и руководства содержат ровно те слова, которыми человек формулирует запрос,
/// и исключать документацию из поиска означало бы терять самый естественный путь к нужному
/// месту в дереве. Прочие текстовые файлы (данные, журналы, произвольные конфигурации)
/// намеренно не индексируются: они наполнили бы словарь шумом и снизили бы вес
/// действительно значимых терминов.
fn is_indexable_ext(ext: &str) -> bool {
    lang_for_ext(ext) != "text" || matches!(ext, "md" | "markdown")
}

/// Оставить не более `limit` наиболее частых терминов файла.
///
/// Отбор ведётся по убыванию частоты, а при равной частоте по возрастанию самого термина,
/// поэтому итог полностью определён данными и воспроизводим. Сохраняются именно частые
/// термины: превышение предела указывает на сгенерированный или похожий на данные файл, у
/// которого одиночные редкие строки поискового смысла не несут, тогда как частые слова всё
/// же описывают, о чём этот файл.
fn keep_most_frequent(freq: BTreeMap<String, u32>, limit: usize) -> BTreeMap<String, u32> {
    let mut ordered: Vec<(String, u32)> = freq.into_iter().collect();
    ordered.sort_by(|a, b| b.1.cmp(&a.1).then_with(|| a.0.cmp(&b.0)));
    ordered.truncate(limit);
    ordered.into_iter().collect()
}

/// Разбить текст на термины индекса.
///
/// Разбор идёт в два приёма. Сначала текст режется на слова по любому символу, не
/// являющемуся буквой, цифрой или знаком подчёркивания: так из кода выпадают знаки
/// пунктуации, операторы и разделители, а слово остаётся цельным. Затем каждое слово
/// разбивается на составляющие по знакам подчёркивания и по границам верблюжьего регистра,
/// поскольку в исходном коде смысловая единица почти никогда не совпадает с целым
/// идентификатором: человек ищет `user`, а в коде написано `parseUserName` либо
/// `parse_user_name`, и без разбора составных имён поиск не нашёл бы ни того, ни другого.
/// Составляющие приводятся к нижнему регистру, поэтому регистр записи в исходнике и в
/// запросе значения не имеет.
///
/// Разбор опирается на свойства символов Юникода, а не на диапазон ASCII, поэтому кириллица
/// поддержана наравне с латиницей: слово `разборИмени` даёт составляющие `разбор` и `имени`,
/// а русский текст документации индексируется так же, как английский.
///
/// Аналогичный по назначению подсчёт идентификаторов уже существует в движке извлечения
/// символов, однако воспользоваться им здесь нельзя: он объявлен закрытым внутри своего
/// модуля, не приводит слова к нижнему регистру, не разбивает составные имена и агрегирует
/// частоты по всему дереву сразу, тогда как обратному индексу нужна разбивка по каждому
/// файлу в отдельности.
fn tokenize(text: &str) -> Vec<String> {
    let mut out: Vec<String> = Vec::new();
    let mut word = String::new();
    for ch in text.chars() {
        if ch == '_' || ch.is_alphanumeric() {
            word.push(ch);
        } else if !word.is_empty() {
            split_compound(&word, &mut out);
            word.clear();
        }
    }
    if !word.is_empty() {
        split_compound(&word, &mut out);
    }
    out
}

/// Разбить одно слово на составляющие и добавить пригодные из них в `out`.
///
/// Границей составляющей считаются знак подчёркивания, переход от строчной буквы или цифры
/// к заглавной (`parseUser` даёт `parse` и `user`), а также конец череды заглавных букв
/// перед строчной (`HTTPServer` даёт `http` и `server`). Последнее правило нужно для
/// аббревиатур: без него череда заглавных слилась бы с последующим словом в один термин,
/// которого человек в запросе никогда не наберёт.
fn split_compound(word: &str, out: &mut Vec<String>) {
    for part in word.split('_') {
        if part.is_empty() {
            continue;
        }
        let chars: Vec<char> = part.chars().collect();
        let mut start = 0usize;
        for i in 1..chars.len() {
            let prev = chars[i - 1];
            let cur = chars[i];
            let next = chars.get(i + 1).copied();
            let lower_to_upper = !prev.is_uppercase() && cur.is_uppercase();
            let acronym_boundary =
                prev.is_uppercase() && cur.is_uppercase() && next.is_some_and(|n| n.is_lowercase());
            if lower_to_upper || acronym_boundary {
                push_term(&chars[start..i], out);
                start = i;
            }
        }
        push_term(&chars[start..], out);
    }
}

/// Добавить составляющую в перечень терминов, если она пригодна для индекса.
///
/// Отбрасывается всё короче [`MIN_TERM_CHARS`] символов, а также составляющая, в которой
/// нет ни одной буквы. Второе условие снимает числовые литералы, счётчики версий и остатки
/// шестнадцатеричных значений: как термины запроса они бесполезны, а объём индекса
/// увеличивают заметно. При этом смешанные записи вроде `utf8` сохраняются целиком, так как
/// буква в них присутствует.
fn push_term(chars: &[char], out: &mut Vec<String>) {
    if chars.len() < MIN_TERM_CHARS {
        return;
    }
    if !chars.iter().any(|c| c.is_alphabetic()) {
        return;
    }
    out.push(chars.iter().flat_map(|c| c.to_lowercase()).collect());
}

#[cfg(test)]
mod tests {
    use super::*;
    use ailc_testkit::TempTree;
    use std::path::Path;

    fn build(dir: &Path) -> LexicalIndex {
        IndexEngine::build(&Ctx::new(dir), &RunInput::default()).unwrap()
    }

    /// Отпечаток выдачи для сравнения на точное совпадение. Оценка сравнивается по
    /// разрядному представлению, а не по округлённой записи, поэтому расхождение в
    /// последнем разряде тоже было бы замечено.
    fn fingerprint(hits: &[Hit]) -> Vec<(String, u64, Vec<String>)> {
        hits.iter()
            .map(|h| (h.file.clone(), h.score.to_bits(), h.matched.clone()))
            .collect()
    }

    /// Основное назначение движка: по слову, входящему в составной идентификатор, находится
    /// файл, где этот идентификатор объявлен. Без разбора составных имён такой поиск не
    /// работал бы вовсе, ведь в исходнике слова `user` отдельно не написано.
    #[test]
    fn построение_индекса_находит_файл_по_слову_из_идентификатора() {
        let t = TempTree::new("index");
        t.write("src/accounts.rs", "fn parseUserName(raw: &str) {}\n");
        t.write("src/geometry.rs", "fn computePolygonArea(sides: u32) {}\n");

        let index = build(t.path());
        assert_eq!(index.documents(), 2, "оба исходника проиндексированы");
        assert!(index.terms() > 0, "словарь индекса не пуст");

        let hits = index.search("user", 5);
        assert_eq!(
            hits.len(),
            1,
            "слово встречается ровно в одном файле: {hits:?}",
        );
        assert_eq!(hits[0].file, "src/accounts.rs");
        assert!(hits[0].score > 0.0, "релевантность положительна");
        assert_eq!(
            hits[0].matched,
            vec!["user".to_string()],
            "совпавшие термины перечислены явно, поэтому выдача объяснима"
        );
    }

    /// Разбор верблюжьего регистра, знаков подчёркивания, аббревиатур и кириллицы. Это
    /// сердце токенизации: от неё зависит, совпадёт ли слово запроса со словом в коде.
    #[test]
    fn разбор_верблюжьего_регистра_даёт_составляющие() {
        assert_eq!(tokenize("parseUserName"), vec!["parse", "user", "name"]);
        assert_eq!(tokenize("parse_user_name"), vec!["parse", "user", "name"]);
        assert_eq!(
            tokenize("HTTPServer_config"),
            vec!["http", "server", "config"]
        );
        assert_eq!(tokenize("разборИмени"), vec!["разбор", "имени"]);
        assert_eq!(
            tokenize("let total = countItems(list);"),
            vec!["let", "total", "count", "items", "list"]
        );
        assert_eq!(
            tokenize("a b cd 42 utf8"),
            vec!["cd", "utf8"],
            "односимвольные остатки и чисто числовые записи терминами не становятся"
        );
    }

    /// Детерминированность выдачи. Требование не декоративное: при равных оценках порядок
    /// не задан природой данных, и без явного разрешения равенства по имени файла выдача
    /// менялась бы между прогонами, а вердикт инструмента перестал бы быть воспроизводимым.
    #[test]
    fn выдача_детерминирована_при_повторном_построении() {
        let t = TempTree::new("index");
        // Три файла с ОДИНАКОВЫМ содержимым дают в точности равные оценки, то есть ровно
        // тот случай, ради которого введено разрешение равенства по имени файла.
        for name in ["src/c.rs", "src/a.rs", "src/b.rs"] {
            t.write(name, "fn handleUserRequest() { let user = 1; }\n");
        }

        let first = build(t.path());
        let second = build(t.path());
        let first_hits = first.search("user request", 10);
        let second_hits = second.search("user request", 10);

        assert_eq!(
            fingerprint(&first_hits),
            fingerprint(&second_hits),
            "повторное построение даёт побайтово ту же выдачу"
        );
        let files: Vec<String> = first_hits.iter().map(|h| h.file.clone()).collect();
        assert_eq!(
            files,
            vec![
                "src/a.rs".to_string(),
                "src/b.rs".to_string(),
                "src/c.rs".to_string()
            ],
            "при равных оценках порядок задан именем файла: {files:?}"
        );
        assert_eq!(first.documents(), second.documents());
        assert_eq!(first.terms(), second.terms());
    }

    /// Запрос без пригодных терминов даёт ПУСТУЮ выдачу. Отсутствие ответа не подменяется
    /// перечнем произвольных файлов: правдоподобная, но не относящаяся к запросу выдача
    /// хуже честного отсутствия результата.
    #[test]
    fn пустой_запрос_даёт_пустую_выдачу() {
        let t = TempTree::new("index");
        t.write("src/main.rs", "fn main() { let counter = 0; }\n");
        let index = build(t.path());

        assert!(index.search("", 5).is_empty(), "пустая строка запроса");
        assert!(
            index.search("   \n\t", 5).is_empty(),
            "только пробельные символы"
        );
        assert!(
            index.search("!!! ??? ...", 5).is_empty(),
            "только пунктуация"
        );
        assert!(index.search("x", 5).is_empty(), "односимвольный запрос");
        assert!(
            index.search("counter", 0).is_empty(),
            "нулевой предел выдачи соблюдается"
        );
        assert!(
            !index.search("counter", 5).is_empty(),
            "осмысленный запрос при тех же условиях результат даёт"
        );
    }

    /// Тестовые файлы в индекс не попадают, поскольку индекс описывает продукт. Фикстуры
    /// содержат те же слова, что и прикладной код, и, попав в индекс, вытесняли бы
    /// настоящие места из верхних строк выдачи.
    #[test]
    fn тестовые_файлы_в_индекс_не_попадают() {
        let t = TempTree::new("index");
        t.write("src/payments.rs", "fn productionMarker() {}\n");
        t.write("tests/fixture.rs", "fn productionMarker() {}\n");
        t.write("pkg/handler_test.go", "func productionMarker() {}\n");
        t.write(
            "web/button.test.ts",
            "export function productionMarker() {}\n",
        );

        let index = build(t.path());
        assert_eq!(
            index.documents(),
            1,
            "проиндексирован только прод-исходник, тестовые файлы отсеяны"
        );
        let hits = index.search("marker", 10);
        let files: Vec<String> = hits.iter().map(|h| h.file.clone()).collect();
        assert_eq!(files, vec!["src/payments.rs".to_string()], "{files:?}");
    }

    /// Разметка Markdown индексируется наравне с кодом, а посторонние текстовые файлы нет.
    /// Документация содержит ровно те слова, которыми человек формулирует запрос, тогда как
    /// данные и журналы наполнили бы словарь шумом.
    #[test]
    fn документация_индексируется_а_посторонние_данные_нет() {
        let t = TempTree::new("index");
        t.write(
            "docs/руководство.md",
            "# Порядок выпуска\n\nВыпуск начинается с проверки базовой линии.\n",
        );
        t.write("data/dump.log", "Порядок выпуска проверка базовой линии\n");
        let index = build(t.path());

        let hits = index.search("порядок выпуска", 10);
        let files: Vec<String> = hits.iter().map(|h| h.file.clone()).collect();
        assert_eq!(
            files,
            vec!["docs/руководство.md".to_string()],
            "по документации искать можно, по журналу нет: {files:?}"
        );
        assert_eq!(
            hits[0].matched,
            vec!["выпуска".to_string(), "порядок".to_string()],
            "совпали оба термина запроса, кириллица разобрана наравне с латиницей"
        );
        assert!(
            index.truncated_files().is_empty(),
            "малые файлы предел терминов не превышают"
        );
    }
}
