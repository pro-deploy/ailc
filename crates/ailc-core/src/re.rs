//! Компиляция встроенных паттернов правил БЕЗ аварийного завершения.
//!
//! Паттерны правил суть статические литералы, выверенные при сборке, поэтому исторически
//! они компилировались через `unwrap`/`expect`. Формально это корректно: невалидный
//! литерал есть ошибка программиста. Практически же такой вызов остаётся аварийной точкой
//! в коде, который обрабатывает ЧУЖОЙ репозиторий, а сервер протокола MCP живёт одним
//! процессом на весь сеанс работы среды разработки. Цена паники здесь несоизмерима с
//! ценой пропуска одного правила: в первом случае обрывается сеанс и человек теряет
//! контекст, во втором молча деградирует одна проверка.
//!
//! Поэтому компиляция возвращает `Option`, а несобравшийся паттерн исключает СВОЁ правило
//! и не влияет на остальные. Чтобы деградация не осталась незамеченной, полнота набора
//! закрепляется тестом `все_встроенные_паттерны_компилируются`: сломанный литерал валит
//! непрерывную интеграцию, а не работу пользователя.

use regex::Regex;

/// Скомпилировать встроенный паттерн. `None` означает, что паттерн невалиден и правило,
/// которое на нём построено, в этом прогоне не участвует.
pub fn compile(pattern: &str) -> Option<Regex> {
    Regex::new(pattern).ok()
}

/// Скомпилировать набор паттернов, отбросив невалидные.
pub fn compile_all<'a>(patterns: impl IntoIterator<Item = &'a str>) -> Vec<Regex> {
    patterns.into_iter().filter_map(compile).collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn валидный_паттерн_компилируется() {
        assert!(compile(r"^\d+$").is_some());
    }

    #[test]
    fn невалидный_паттерн_даёт_none_а_не_панику() {
        assert!(compile(r"([a-z").is_none());
    }

    #[test]
    fn набор_отбрасывает_только_невалидные() {
        let v = compile_all([r"^a$", r"([b", r"^c$"]);
        assert_eq!(v.len(), 2, "невалидный паттерн исключён, остальные собраны");
    }
}
