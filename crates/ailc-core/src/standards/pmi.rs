//!
//! Программа и методика испытаний ценна не изложением намерений, а проверяемостью, поэтому
//! объект испытаний определяется из модели проекта: наименование, версия и состояние
//! истории изменений устанавливаются однозначно, и подменить испытуемый объект незаметно
//! становится нельзя. Объём испытаний строится как черновик из выявленных связей и рисков,
//! однако утверждается человеком, поскольку решение о достаточности проверок остаётся
//! ответственностью людей, а не следствием сканирования кода.

