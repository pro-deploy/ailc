//! ДЕЙСТВУЮЩИЙ СТАНДАРТ. Требования к содержанию программы и методики испытаний
//! исторически устанавливались пунктом 2.14 руководящего документа РД 50-34.698-90.
//! В Российской Федерации этот руководящий документ заменён на ГОСТ Р 59795-2021,
//! введённый приказом Росстандарта от 25 октября 2021 года № 1297-ст и действующий
