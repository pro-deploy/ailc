//! Декларация руководства пользователя по ГОСТ Р 59795-2021.
//!
//! ДЕЙСТВУЮЩИЙ СТАНДАРТ. Требования к содержанию руководства пользователя исторически
//! устанавливались пунктом 3.4 руководящего документа РД 50-34.698-90. В Российской
//! Федерации этот руководящий документ заменён на ГОСТ Р 59795-2021, введённый приказом
//! Росстандарта от 25 октября 2021 года № 1297-ст и действующий с 30 апреля 2022 года.
//! Декларация построена по действующему стандарту, а ссылка на пункт руководящего
//! документа сохранена в изложении, поскольку заказчики нередко ссылаются именно на него.
//!
//! Руководство пользователя описывает систему с той стороны, с которой её видит человек,
//! а не с той, с которой её видит разработчик. Из этого следует распределение источников:
//! состав дистрибутива, порядок проверки работоспособности и перечень эксплуатационной
//! документации выводятся из модели проекта, поскольку установлены сборкой и точками входа
//! однозначно, тогда как уровень подготовки пользователя, порядок выполнения операций и
//! рекомендации по освоению кодом не выражаются ни в какой форме и подлежат опросу.

