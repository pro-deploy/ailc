    /// Прежде оба вида писались в один файл `run.json`, ключ проверялся на точное совпадение,
    /// и каждая запись затирала запись другого вида. При обычном порядке работы (построение
    /// плана, затем правка, затем проверка готовности) кэш поэтому почти всегда промахивался:
    /// прогон читал файл, оставленный прогоном другого вида. Заявленная инкрементальность в
    /// таком виде не работала вовсе, хотя отпечаток дерева совпадал.
    #[test]
    fn разные_виды_прогона_не_вытесняют_друг_друга() {
        let c = ctx("kinds");
        let f = fingerprint(&c).expect("отпечаток снимается");
        // Ключи повторяют те, что строят вызывающие: `engines::gate` и `cached_run`.
        let gate_key = format!("gate|{f}|high|quality,security");
        let checks_key = format!("{f}|quality.check,security.scan");
        save_run(&c, &gate_key, &"гейтовый прогон".to_string()).unwrap();
        save_run(&c, &checks_key, &"прогон набора проверок".to_string()).unwrap();

        let gate: Option<String> = load_run(&c, &gate_key);
        let checks: Option<String> = load_run(&c, &checks_key);
        assert_eq!(
            gate.as_deref(),
            Some("гейтовый прогон"),
            "гейтовый прогон обязан читаться после записи прогона набора проверок"
        );
        assert_eq!(
            checks.as_deref(),
            Some("прогон набора проверок"),
            "прогон набора проверок обязан читаться после записи гейтового прогона"
        );

        // Третий вид кэша, которого сегодня нет, тоже обязан ужиться с первыми двумя: имя
        // файла вычисляется из ключа, поэтому отдельное место он получает сам.
        let third_key = format!("будущий-вид|{f}");
        save_run(&c, &third_key, &"третий вид".to_string()).unwrap();
        assert_eq!(
            load_run::<String>(&c, &gate_key).as_deref(),
            Some("гейтовый прогон"),
            "появление третьего вида кэша не имеет права вытеснять прежние"
        );
        cleanup(&c);
    }

    /// Файлы прогонов не имеют права копиться в пользовательском каталоге кэша без предела:
    /// ключ меняется при каждой правке дерева, то есть без уборки каталог рос бы на файл с
    /// каждой правкой кода. При этом только что записанный прогон обязан пережить уборку.
    #[test]
    fn файлы_прогонов_не_копятся_без_предела() {
        let c = ctx("prune");
        let last = MAX_RUN_FILES + 7;
        for i in 0..=last {
            save_run(
                &c,
                &format!("gate|отпечаток-{i}|high|quality"),
                &format!("прогон {i}"),
            )
            .unwrap();
        }
        let dir = cache_dir(&c).expect("каталог кэша определяется");
        let count = std::fs::read_dir(&dir)
            .unwrap()
            .flatten()
            .filter(|e| e.file_name().to_string_lossy().starts_with(RUN_PREFIX))
            .count();
        assert!(
            count <= MAX_RUN_FILES,
            "файлов прогона осталось {count}, а разрешено не более {MAX_RUN_FILES}"
        );
        assert_eq!(
            load_run::<String>(&c, &format!("gate|отпечаток-{last}|high|quality")).as_deref(),
            Some(format!("прогон {last}").as_str()),
            "последний записанный прогон обязан пережить уборку каталога"
        );
        cleanup(&c);
    }

    /// Файл кэша прежнего формата, где все виды прогона делили одно имя, читать больше
    /// некому: он остаётся лежать в пользовательском каталоге мёртвым грузом и потому
    /// удаляется при первой же записи прогона.
    #[test]
    fn файл_прежнего_формата_убирается() {
        let c = ctx("legacy");
        let key = format!("gate|{}|high|quality", fingerprint(&c).unwrap());
        save_run(&c, &key, &"свежий прогон".to_string()).unwrap();
        let dir = cache_dir(&c).expect("каталог кэша определяется");
        std::fs::write(dir.join(LEGACY_RUN_FILE), "{}").unwrap();
        save_run(&c, &key, &"свежий прогон".to_string()).unwrap();
        assert!(
            !dir.join(LEGACY_RUN_FILE).exists(),
            "файл прежнего формата обязан быть убран"
        );
        cleanup(&c);
    }

    /// Число каталогов чужих проектов ограничено сверху, а не только сроком давности.
    /// Проверяется на заведомо свежих каталогах, которые по сроку удалить нельзя: именно так
    /// и выглядит накопление от машинных прогонов, где каталоги появляются быстрее, чем
    /// стареют. Одновременно проверяется, что каталог текущего проекта переживает уборку.
    #[test]
    /// Уборка проверяется как самостоятельная функция в СОБСТВЕННОМ временном каталоге, а не
    /// через запись кэша: запись пошла бы в общий пользовательский каталог, где соседние
    /// тесты держат свои каталоги, и уборка по пределу удаляла бы их вместе с мусором этого
    /// теста. Изоляция здесь не удобство, а условие независимости тестов друг от друга.
    fn число_каталогов_проектов_ограничено_сверху() {
        let parent = std::env::temp_dir().join(format!(
            "ailc-prune-{}-{}",
            std::process::id(),
            std::time::SystemTime::now()
                .duration_since(std::time::UNIX_EPOCH)
                .unwrap()
                .as_nanos()
        ));
        let current = parent.join("текущий");
        std::fs::create_dir_all(&current).unwrap();
        let мусор: Vec<_> = (0..MAX_PROJECT_DIRS + 20)
            .map(|i| parent.join(format!("проверка-предела-{i:04}")))
            .collect();
        for p in &мусор {
            std::fs::create_dir_all(p).unwrap();
            std::fs::write(p.join("run-0.json"), "{}").unwrap();
        }

        prune_projects(&current);

        let осталось = мусор.iter().filter(|p| p.exists()).count();
        assert_eq!(
            осталось, MAX_PROJECT_DIRS,
            "сверх предела каталоги удаляются, а предел сохраняется целиком"
        );
        assert!(
            current.exists(),
            "каталог текущего проекта обязан пережить уборку"
        );
        std::fs::remove_dir_all(&parent).ok();
    }

    /// Кэш прежнего РАЗМЕЩЕНИЯ, лежащий внутри проверяемого репозитория, тоже обязан
    /// убираться: уборка пользовательского каталога его не видит, и на всякой установке,
    /// работавшей с прежними версиями, он сохранялся бы навсегда. Одновременно проверяется
    /// граница удаления: посторонний файл, положенный в тот же каталог человеком, остаётся
    /// нетронутым вместе с каталогом.
    #[test]
    fn кэш_прежнего_размещения_внутри_репозитория_убирается() {
        let c = ctx("legacy-in-repo");
        let repo_cache = c.root.join(".ailc").join("cache");
        std::fs::create_dir_all(&repo_cache).unwrap();
        std::fs::write(repo_cache.join(LEGACY_RUN_FILE), "{}").unwrap();
        std::fs::write(repo_cache.join("run-0123456789abcdef.json"), "{}").unwrap();
        std::fs::write(repo_cache.join("заметка.txt"), "не наше").unwrap();

        let key = format!("gate|{}|high|quality", fingerprint(&c).unwrap());
        save_run(&c, &key, &"свежий прогон".to_string()).unwrap();

        assert!(
            !repo_cache.join(LEGACY_RUN_FILE).exists(),
            "файл прежнего формата внутри репозитория обязан быть убран"
        );
        assert!(
            !repo_cache.join("run-0123456789abcdef.json").exists(),
            "файл кэша прогона внутри репозитория обязан быть убран"
        );
        assert!(
            repo_cache.join("заметка.txt").exists(),
            "посторонний файл удалять не имеем права"
        );
        assert!(
            repo_cache.exists(),
            "непустой каталог остаётся вместе с посторонним файлом"
        );
        cleanup(&c);
    }
