    /// Убрать за тестом рабочее дерево ВМЕСТЕ с каталогом кэша.
    ///
    /// Каталог кэша лежит вне проекта и по имени, вычисленному из пути проекта, а путь у
    /// каждого теста свой. Без этой уборки прогон тестов оставлял бы в пользовательском кэше
    /// по каталогу на каждый тест, то есть повторял бы ровно ту болезнь накопления, от
    /// которой избавлен рабочий код. Порядок действий важен: каталог кэша определяется по
    /// каноническому пути проекта, поэтому вычислить его нужно ПОКА проект ещё существует.
    fn cleanup(c: &Ctx) {
        if let Some(dir) = cache_dir(c) {
            std::fs::remove_dir_all(dir).ok();
        }
        std::fs::remove_dir_all(&c.root).ok();
    }

    /// Время изменения файла как длительность от эпохи (для восстановления).
    fn filetime_of(meta: &std::fs::Metadata) -> std::time::Duration {
        meta.modified()
            .ok()
            .and_then(|m| m.duration_since(UNIX_EPOCH).ok())
            .unwrap_or_default()
    }

    /// Восстановить время изменения файла. Реализовано через внешнюю утилиту `touch`, чтобы
    /// не вводить зависимость ради одного теста; на платформах без неё тест всё равно
    /// осмыслен, поскольку содержимое изменилось.
    fn set_mtime(path: &std::path::Path, when: std::time::Duration) {
        let secs = when.as_secs();
        let _ = std::process::Command::new("touch")
            .arg("-t")
            .arg(format_stamp(secs))
            .arg(path)
            .status();
    }

    /// Метка времени в формате `[[CC]YY]MMDDhhmm[.SS]` для утилиты `touch`.
    fn format_stamp(secs: u64) -> String {
        // Достаточно грубого преобразования: тесту нужна ВОСПРОИЗВОДИМАЯ метка, а не точная.
        let days = secs / 86_400;
        let (y, m, d) = civil_from_days(days as i64);
        let rest = secs % 86_400;
        format!(
            "{:04}{:02}{:02}{:02}{:02}.{:02}",
            y,
            m,
            d,
            rest / 3600,
            (rest % 3600) / 60,
            rest % 60
        )
    }

    /// Обратное преобразование числа суток от эпохи в календарную дату.
    fn civil_from_days(z: i64) -> (i64, u32, u32) {
        let z = z + 719_468;
        let era = if z >= 0 { z } else { z - 146_096 } / 146_097;
        let doe = z - era * 146_097;
        let yoe = (doe - doe / 1460 + doe / 36_524 - doe / 146_096) / 365;
        let y = yoe + era * 400;
        let doy = doe - (365 * yoe + yoe / 4 - yoe / 100);
        let mp = (5 * doy + 2) / 153;
        let d = (doy - (153 * mp + 2) / 5 + 1) as u32;
        let m = if mp < 10 { mp + 3 } else { mp - 9 } as u32;
        (if m <= 2 { y + 1 } else { y }, m, d)
    }

